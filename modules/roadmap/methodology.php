function roadmapParseDate(?string $value): ?DateTimeImmutable
{
    $value = trim((string) $value);
    if ($value === '') {
        return null;
    }

    $date = DateTimeImmutable::createFromFormat('!Y-m-d', $value);
    if (!$date || $date->format('Y-m-d') !== $value) {
        return null;
    }

    return $date;
}

function roadmapDateString(?DateTimeImmutable $date): ?string
{
    return $date ? $date->format('Y-m-d') : null;
}

function roadmapDeveloperEntityKey(int $projectId, string $scope): string
{
    try {
        $token = bin2hex(random_bytes(8));
    } catch (Throwable $exception) {
        $token = str_replace('.', '', uniqid('', true));
    }

    return substr($scope . '-' . $projectId . '-' . $token, 0, 80);
}

function roadmapCollectDepartmentRequirements(
    mixed $selectedDepartmentValues,
    mixed $postedDepartmentCounts,
    array $postedDepartmentAllocations,
    int $postedDeveloperCapacity,
    ?string &$error
): array {
    $error = null;
    $departmentRequirements = [];

    if (!is_array($selectedDepartmentValues) || !is_array($postedDepartmentCounts)) {
        $selectedDepartmentValues = [];
        $postedDepartmentCounts = [];
    }

    foreach (array_unique($selectedDepartmentValues) as $selectedDepartment) {
        $department = projectWorkflowDepartmentLabel((string) $selectedDepartment);
        if (!array_key_exists($department, $postedDepartmentAllocations)) {
            $error = 'Every task department must come from this project\'s Developer Allocation.';
            return [];
        }

        $availableCount = max(0, (int) $postedDepartmentAllocations[$department]);
        $requiredCount = max(0, (int) ($postedDepartmentCounts[$department] ?? 0));
        if ($availableCount <= 0 || $requiredCount < 1 || $requiredCount > $availableCount) {
            $error = $department . ' task headcount must be between 1 and its Developer Allocation limit of ' . $availableCount . '.';
            return [];
        }

        $departmentRequirements[$department] = $requiredCount;
    }

    if ($departmentRequirements === []) {
        $error = 'Select at least one department staffing requirement for this roadmap task.';
        return [];
    }

    if (array_sum($departmentRequirements) > $postedDeveloperCapacity) {
        $error = 'Task headcount cannot exceed the project Developer Allocation capacity of ' . $postedDeveloperCapacity . '.';
        return [];
    }

    return $departmentRequirements;
}

function roadmapDaysBetween(string $start, string $end): int
{
    $startDate = roadmapParseDate($start);
    $endDate = roadmapParseDate($end);
    if (!$startDate || !$endDate || $endDate < $startDate) {
        return 0;
    }

    return ((int) $startDate->diff($endDate)->format('%a')) + 1;
}

function roadmapPhaseIndicator(string $status): array
{
    $status = strtolower(trim($status));

    if (in_array($status, ['completed', 'done'], true)) {
        return [
            'key' => 'done',
            'label' => 'Done',
            'icon' => 'fas fa-circle-check',
        ];
    }

    if ($status === 'on_hold') {
        return [
            'key' => 'pending',
            'label' => 'Pending Review',
            'icon' => 'fas fa-clock',
        ];
    }

    if (in_array($status, ['in_progress', 'pending'], true)) {
        return [
            'key' => 'in-progress',
            'label' => 'In Progress',
            'icon' => 'fas fa-spinner',
        ];
    }

    return [
        'key' => 'not-started',
        'label' => 'Not Yet Started',
        'icon' => 'far fa-circle',
    ];
}

function roadmapMonitoringTaskIndicator(?string $workflowStatus, string $roadmapStatus): array
{
    $workflowStatus = strtolower(trim((string) $workflowStatus));
    $roadmapStatus = strtolower(trim($roadmapStatus));

    if ($workflowStatus !== '') {
        if (in_array($workflowStatus, ['completed', 'merged', 'ready_for_release'], true)) {
            return ['key' => 'done', 'label' => 'Done'];
        }

        if (in_array($workflowStatus, ['blocked', 'overdue', 'sul_revision', 'qa_failed'], true)) {
            return ['key' => 'pending', 'label' => 'Blocked / Revision'];
        }

        if (in_array($workflowStatus, ['review', 'in_review', 'for_review', 'qa_testing', 'qa_passed', 'architect_review'], true)) {
            return ['key' => 'pending', 'label' => 'Pending Review'];
        }

        if ($workflowStatus === 'in_progress') {
            return ['key' => 'in-progress', 'label' => 'In Progress'];
        }

        return ['key' => 'not-started', 'label' => 'Not Yet Started'];
    }

    if ($roadmapStatus === 'completed') {
        return ['key' => 'done', 'label' => 'Done'];
    }

    if (in_array($roadmapStatus, ['blocked', 'on_hold'], true)) {
        return ['key' => 'pending', 'label' => 'Blocked / Revision'];
    }

    if ($roadmapStatus === 'in_progress') {
        return ['key' => 'in-progress', 'label' => 'In Progress'];
    }

    return ['key' => 'not-started', 'label' => 'Not Yet Started'];
}

function roadmapMonitoringProfileUrl(?string $profilePic): string
{
    $profilePic = trim((string) $profilePic);
    if ($profilePic === '') {
        return '';
    }

    if (preg_match('#^https?://#i', $profilePic)) {
        return $profilePic;
    }

    return BASE_URL . ltrim(str_replace('\\', '/', $profilePic), '/');
}

function roadmapMonitoringInitials(?string $name): string
{
    $parts = preg_split('/\s+/', trim((string) $name), -1, PREG_SPLIT_NO_EMPTY) ?: [];
    if ($parts === []) {
        return '?';
    }

    $substring = function_exists('mb_substr') ? 'mb_substr' : 'substr';
    $uppercase = function_exists('mb_strtoupper') ? 'mb_strtoupper' : 'strtoupper';
    $first = $substring((string) $parts[0], 0, 1);
    $last = count($parts) > 1 ? $substring((string) $parts[count($parts) - 1], 0, 1) : '';
    return $uppercase($first . $last);
}

function roadmapMonitoringPhaseIndicator(array $phase, bool $departmentOnly = false): array
{
    $tasks = is_array($phase['tasks'] ?? null) ? $phase['tasks'] : [];
    if ($departmentOnly) {
        $tasks = array_values(array_filter(
            $tasks,
            static fn(array $task): bool => !empty($task['is_sul_department_task'])
        ));
    }
    if ($tasks === []) {
        if ($departmentOnly) {
            return ['key' => 'not-started', 'label' => 'No Department Tasks', 'icon' => 'fas fa-minus'];
        }
        return roadmapPhaseIndicator((string) ($phase['status'] ?? 'planned'));
    }

    $counts = ['not-started' => 0, 'in-progress' => 0, 'pending' => 0, 'done' => 0];
    foreach ($tasks as $task) {
        $key = (string) ($task['monitoring_status_key'] ?? 'not-started');
        if (array_key_exists($key, $counts)) {
            $counts[$key]++;
        }
    }

    if ($counts['done'] === count($tasks)) {
        return ['key' => 'done', 'label' => 'Done', 'icon' => 'fas fa-circle-check'];
    }

    if ($counts['pending'] > 0) {
        return ['key' => 'pending', 'label' => 'Pending / Blocked', 'icon' => 'fas fa-clock'];
    }

    if ($counts['in-progress'] > 0 || $counts['done'] > 0) {
        return ['key' => 'in-progress', 'label' => 'In Progress', 'icon' => 'fas fa-spinner'];
    }

    return ['key' => 'not-started', 'label' => 'Not Yet Started', 'icon' => 'far fa-circle'];
}

function roadmapProjectAccessClause(mysqli|PgsqlMysqliCompatConnection $conn, array $user, string $alias = 'p'): string
{
    $role = (string) ($user['role'] ?? '');
    $userId = (int) ($user['id'] ?? 0);

    if ($role === 'architect') {
        return "({$alias}.architect_id = {$userId} OR {$alias}.architect_id IS NULL)";
    }

    if ($role === 'sales') {
        return "{$alias}.status != 'cancelled'";
    }

    if ($role === 'sul') {
        $department = projectWorkflowDepartmentLabel((string) ($user['department'] ?? ''));
        if ($department === '') {
            return '1 = 0';
        }

        $departmentAccess = projectWorkflowProjectDepartmentClause($conn, $alias, $department);
        return "({$alias}.status != 'cancelled' AND {$departmentAccess})";
    }

    return "{$alias}.status != 'cancelled'";
}

function roadmapValidatePhase(array $project, DateTimeImmutable $start, DateTimeImmutable $end): ?string
{
    if ($end < $start) {
        return 'Phase end date must be on or after the phase start date.';
    }

    $projectStart = roadmapParseDate($project['timeline_start'] ?? null);
    $projectEnd = roadmapParseDate($project['timeline_end'] ?? null);

    if ($projectStart && $start < $projectStart) {
        return 'Phase start date cannot be earlier than the project start date.';
    }

    if ($projectEnd && $end > $projectEnd) {
        return 'Phase end date cannot be later than the project end date.';
    }

    return null;
}

function roadmapValidateTask(array $phase, DateTimeImmutable $start, DateTimeImmutable $end): ?string
{
    if ($end < $start) {
        return 'Task end date must be on or after the task start date.';
    }

    $phaseStart = roadmapParseDate($phase['start_date'] ?? null);
    $phaseEnd = roadmapParseDate($phase['end_date'] ?? null);

    if ($phaseStart && $start < $phaseStart) {
        return 'Task start date cannot be earlier than the selected phase start date.';
    }

    if ($phaseEnd && $end > $phaseEnd) {
        return 'Task end date cannot be later than the selected phase end date.';
    }

    return null;
}

