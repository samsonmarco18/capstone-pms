        SELECT p.*, c.name AS client_name
        FROM projects p
        JOIN clients c ON c.id = p.client_id
        WHERE p.id = {$projectId} AND {$access}
        LIMIT 1
    ");

    return $project ? ($project->fetch_assoc() ?: null) : null;
}

