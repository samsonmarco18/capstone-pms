function roadmapParseDate(?string $value): ?DateTimeImmutable
{
    $value = trim((string) $value);
    if ($value === '') {
        return null;
    }

    $date = DateTimeImmutable::createFromFormat('!Y-m-d', $value);
    if (!$date || $date->format('Y-m-d') !== $value) {
        return null;
    }

    return $date;
}

function roadmapDateString(?DateTimeImmutable $date): ?string
{
    return $date ? $date->format('Y-m-d') : null;
}

function roadmapDaysBetween(string $start, string $end): int
{
    $startDate = roadmapParseDate($start);
    $endDate = roadmapParseDate($end);
    if (!$startDate || !$endDate || $endDate < $startDate) {
        return 0;
    }

    return ((int) $startDate->diff($endDate)->format('%a')) + 1;
}

function roadmapProjectAccessClause(mysqli|PgsqlMysqliCompatConnection $conn, array $user, string $alias = 'p'): string
{
    $role = (string) ($user['role'] ?? '');
    $userId = (int) ($user['id'] ?? 0);

    if ($role === 'architect') {
        return "({$alias}.architect_id = {$userId} OR {$alias}.architect_id IS NULL)";
    }

    if ($role === 'sales') {
        return "{$alias}.status != 'cancelled'";
    }

    return "{$alias}.status != 'cancelled'";
}

function roadmapValidatePhase(array $project, DateTimeImmutable $start, DateTimeImmutable $end): ?string
{
    if ($end < $start) {
        return 'Phase end date must be on or after the phase start date.';
    }

    $projectStart = roadmapParseDate($project['timeline_start'] ?? null);
    $projectEnd = roadmapParseDate($project['timeline_end'] ?? null);

    if ($projectStart && $start < $projectStart) {
        return 'Phase start date cannot be earlier than the project start date.';
    }

    if ($projectEnd && $end > $projectEnd) {
        return 'Phase end date cannot be later than the project end date.';
    }

    return null;
}

function roadmapValidateTask(array $phase, DateTimeImmutable $start, DateTimeImmutable $end): ?string
{
    if ($end < $start) {
        return 'Task end date must be on or after the task start date.';
    }

    $phaseStart = roadmapParseDate($phase['start_date'] ?? null);
    $phaseEnd = roadmapParseDate($phase['end_date'] ?? null);

    if ($phaseStart && $start < $phaseStart) {
        return 'Task start date cannot be earlier than the selected phase start date.';
    }

    if ($phaseEnd && $end > $phaseEnd) {
        return 'Task end date cannot be later than the selected phase end date.';
    }

    return null;
}

