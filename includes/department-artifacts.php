function departmentArtifactParseRequirements(?string $rawFeatures): array
{
    $raw = trim((string) $rawFeatures);
    if ($raw === '') {
        return [];
    }

    $items = [];
    $seen = [];
    foreach ((preg_split('/\R/', $raw) ?: []) as $line) {
        $line = trim((string) $line);
        if ($line === '') {
            continue;
        }

        if (preg_match('/^(additional requirements|budget)\s*:/i', $line)) {
            break;
        }

        $line = trim((string) preg_replace('/^\s*(?:[-*]|\d+[\.)])\s*/', '', $line));
        if ($line === '') {
            continue;
        }

        $normalized = strtolower(preg_replace('/\s+/', ' ', $line));
        if (isset($seen[$normalized])) {
            continue;
        }

        $seen[$normalized] = true;
        $items[] = $line;
    }

    return $items;
}

function departmentArtifactAdditionalRequirements(?string $rawFeatures): string
{
    if (preg_match('/Additional Requirements:\s*(.*?)(?:\R{2,}Budget:|\z)/is', (string) $rawFeatures, $matches)) {
        return trim((string) ($matches[1] ?? ''));
    }

    return '';
}

function departmentArtifactFetchForTask(mysqli|PgsqlMysqliCompatConnection $conn, int $taskId): array
{
    departmentArtifactEnsureSchema($conn);

    $stmt = $conn->prepare(
        'SELECT tda.*, u.full_name AS user_name
         FROM task_department_artifacts tda
         LEFT JOIN users u ON u.id = tda.user_id
         WHERE tda.task_id = ?
         ORDER BY tda.created_at DESC, tda.id DESC'
    );
    if ($stmt === false) {
        return [];
    }

    $stmt->bind_param('i', $taskId);
    $stmt->execute();
    $result = $stmt->get_result();

    $artifacts = [];
    while ($row = $result->fetch_assoc()) {
        $filePath = trim((string) ($row['file_path'] ?? ''));
        $row['file_url'] = $filePath !== '' ? BASE_URL . ltrim($filePath, '/') : '';
        $artifacts[] = $row;
    }
    $stmt->close();

    return $artifacts;
}
