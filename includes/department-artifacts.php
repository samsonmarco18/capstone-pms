function departmentArtifactEnsureSchema(mysqli|PgsqlMysqliCompatConnection $conn): void
{
    static $done = false;
    if ($done) {
        return;
    }
    $done = true;

    if (dbTableExists($conn, 'task_department_artifacts')) {
        return;
    }

    if (defined('DB_DRIVER') && DB_DRIVER === 'pgsql') {
        $conn->query(
            "CREATE TABLE IF NOT EXISTS task_department_artifacts (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                task_id INT NOT NULL,
                project_id INT NOT NULL,
                user_id INT NULL,
                department VARCHAR(100) NOT NULL,
                artifact_type VARCHAR(50) NOT NULL DEFAULT 'department_handoff',
                title VARCHAR(255) NOT NULL,
                file_path VARCHAR(500),
                original_file_name VARCHAR(255),
                file_type VARCHAR(100),
                file_size BIGINT,
                external_url VARCHAR(500),
                notes TEXT,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE,
                FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
                FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
            )"
        );
        $conn->query('CREATE INDEX IF NOT EXISTS task_department_artifacts_task_idx ON task_department_artifacts (task_id)');
        $conn->query('CREATE INDEX IF NOT EXISTS task_department_artifacts_project_idx ON task_department_artifacts (project_id)');
        $conn->query('CREATE INDEX IF NOT EXISTS task_department_artifacts_department_idx ON task_department_artifacts (department)');
        return;
    }

    $conn->query(
        "CREATE TABLE IF NOT EXISTS task_department_artifacts (
            id INT PRIMARY KEY AUTO_INCREMENT,
            task_id INT NOT NULL,
            project_id INT NOT NULL,
            user_id INT NULL,
            department VARCHAR(100) NOT NULL,
            artifact_type VARCHAR(50) NOT NULL DEFAULT 'department_handoff',
            title VARCHAR(255) NOT NULL,
            file_path VARCHAR(500),
            original_file_name VARCHAR(255),
            file_type VARCHAR(100),
            file_size BIGINT,
            external_url VARCHAR(500),
            notes TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE,
            FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
            INDEX idx_task_department_artifacts_task (task_id),
            INDEX idx_task_department_artifacts_project (project_id),
            INDEX idx_task_department_artifacts_department (department)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );
}

