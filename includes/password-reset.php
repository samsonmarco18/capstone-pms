<?php
declare(strict_types=1);

require_once __DIR__ . '/auth.php';

function ensurePasswordResetRequestsTable(): bool
{
    static $ensured = false;

    if ($ensured) {
        return true;
    }

    try {
        $conn = getConnection();

        if (DB_DRIVER === 'pgsql') {
            $sql = "
                CREATE TABLE IF NOT EXISTS password_reset_requests (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INT NOT NULL,
                    requested_email VARCHAR(100) NOT NULL,
                    status VARCHAR(20) NOT NULL DEFAULT 'pending',
                    request_source VARCHAR(50) NOT NULL DEFAULT 'login',
                    admin_note TEXT,
                    last_error TEXT,
                    processed_by INT NULL,
                    requested_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    processed_at TIMESTAMP NULL,
                    temp_password_sent_at TIMESTAMP NULL,
                    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
                    FOREIGN KEY (processed_by) REFERENCES users(id) ON DELETE SET NULL
                )
            ";
            $indexStatements = [
                'CREATE INDEX IF NOT EXISTS password_reset_requests_idx_user_id ON password_reset_requests (user_id)',
                'CREATE INDEX IF NOT EXISTS password_reset_requests_idx_status ON password_reset_requests (status)',
                'CREATE INDEX IF NOT EXISTS password_reset_requests_idx_requested_at ON password_reset_requests (requested_at)',
            ];
        } else {
            $sql = "
                CREATE TABLE IF NOT EXISTS password_reset_requests (
                    id INT PRIMARY KEY AUTO_INCREMENT,
                    user_id INT NOT NULL,
                    requested_email VARCHAR(100) NOT NULL,
                    status VARCHAR(20) NOT NULL DEFAULT 'pending',
                    request_source VARCHAR(50) NOT NULL DEFAULT 'login',
                    admin_note TEXT,
                    last_error TEXT,
                    processed_by INT NULL,
                    requested_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    processed_at DATETIME NULL,
                    temp_password_sent_at DATETIME NULL,
                    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
                    FOREIGN KEY (processed_by) REFERENCES users(id) ON DELETE SET NULL,
                    INDEX idx_password_reset_requests_user_id (user_id),
                    INDEX idx_password_reset_requests_status (status),
                    INDEX idx_password_reset_requests_requested_at (requested_at)
                ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
            ";
            $indexStatements = [];
        }

        if ($conn->query($sql) === false) {
            throw new RuntimeException('Failed creating password_reset_requests table.');
        }

        foreach ($indexStatements as $statement) {
            $conn->query($statement);
        }

        $ensured = true;
        return true;
    } catch (Throwable $e) {
        error_log('ensurePasswordResetRequestsTable error: ' . $e->getMessage());
        return false;
    }
}

function requestPasswordResetForEmail(string $email): array
{
    $normalizedEmail = trim($email);
    $genericMessage = 'If the account exists, your password reset request has been sent to the administrator.';

    if ($normalizedEmail === '' || !filter_var($normalizedEmail, FILTER_VALIDATE_EMAIL)) {
        return ['success' => true, 'message' => $genericMessage];
    }

    if (!ensurePasswordResetRequestsTable()) {
        return ['success' => true, 'message' => $genericMessage];
    }

    try {
        $conn = getConnection();
        $stmt = $conn->prepare('SELECT id, full_name, email, status FROM users WHERE LOWER(email) = LOWER(?) LIMIT 1');
        if ($stmt === false) {
            return ['success' => true, 'message' => $genericMessage];
        }

        $stmt->bind_param('s', $normalizedEmail);
        $stmt->execute();
        $result = $stmt->get_result();
        $user = $result ? ($result->fetch_assoc() ?: null) : null;
        $stmt->close();

        if (!$user) {
            logActivity(null, 'password_reset_requested_unknown_email', 'users', null, null, ['email' => $normalizedEmail], 'warning');
            return ['success' => true, 'message' => $genericMessage];
        }

        $requestId = null;
        $existingStmt = $conn->prepare(
            "SELECT id
             FROM password_reset_requests
             WHERE user_id = ? AND status IN ('pending', 'failed')
             ORDER BY requested_at DESC
             LIMIT 1"
        );
        if ($existingStmt !== false) {
            $existingStmt->bind_param('i', $user['id']);
            $existingStmt->execute();
            $existingResult = $existingStmt->get_result();
            $existing = $existingResult ? ($existingResult->fetch_assoc() ?: null) : null;
            $existingStmt->close();

            if ($existing) {
                $requestId = (int) $existing['id'];
                $resetStmt = $conn->prepare(
                    "UPDATE password_reset_requests
                     SET status = 'pending',
                         admin_note = NULL,
                         last_error = NULL,
                         processed_by = NULL,
                         processed_at = NULL,
                         temp_password_sent_at = NULL,
                         requested_at = CURRENT_TIMESTAMP
                     WHERE id = ?"
                );
                if ($resetStmt !== false) {
                    $resetStmt->bind_param('i', $requestId);
                    $resetStmt->execute();
                    $resetStmt->close();
                }
            }
        }

        if ($requestId === null) {
            $insertStmt = $conn->prepare(
                'INSERT INTO password_reset_requests (user_id, requested_email, status, request_source)
                 VALUES (?, ?, ?, ?)'
            );
            if ($insertStmt === false) {
                return ['success' => true, 'message' => $genericMessage];
            }

            $status = 'pending';
            $source = 'login';
            $insertStmt->bind_param('isss', $user['id'], $user['email'], $status, $source);
            if ($insertStmt->execute()) {
                $requestId = (int) $insertStmt->insert_id;
                if ($requestId === 0) {
                    $fallbackStmt = $conn->prepare(
                        'SELECT id FROM password_reset_requests WHERE user_id = ? ORDER BY requested_at DESC LIMIT 1'
                    );
                    if ($fallbackStmt !== false) {
                        $fallbackStmt->bind_param('i', $user['id']);
                        $fallbackStmt->execute();
                        $fallbackResult = $fallbackStmt->get_result();
                        $fallbackRow = $fallbackResult ? ($fallbackResult->fetch_assoc() ?: null) : null;
                        $requestId = (int) ($fallbackRow['id'] ?? 0);
                        $fallbackStmt->close();
                    }
                }
            }
            $insertStmt->close();
        }

        if ($requestId > 0) {
            notifyAdminsAboutPasswordResetRequest($requestId, $user);
        }

        logActivity(
            (int) $user['id'],
            'password_reset_requested',
            'password_reset_requests',
            $requestId,
            null,
            ['email' => $user['email']],
            'success'
        );

        return ['success' => true, 'message' => $genericMessage];
    } catch (Throwable $e) {
        error_log('requestPasswordResetForEmail error: ' . $e->getMessage());
        return ['success' => true, 'message' => $genericMessage];
    }
}

function notifyAdminsAboutPasswordResetRequest(int $requestId, array $requestingUser): void
{
    try {
        $conn = getConnection();
        $stmt = $conn->prepare("SELECT id FROM users WHERE role = 'admin' AND status = 'active'");
        if ($stmt === false) {
            return;
        }

        $stmt->execute();
        $result = $stmt->get_result();
        $admins = [];
        if ($result) {
            while ($row = $result->fetch_assoc()) {
                $admins[] = (int) ($row['id'] ?? 0);
            }
        }
        $stmt->close();

        $name = trim((string) ($requestingUser['full_name'] ?? 'A user'));
        $email = trim((string) ($requestingUser['email'] ?? ''));
        $message = $name . ' (' . $email . ') requested a password reset.';
        $actionUrl = BASE_URL . 'modules/admin/password-reset-requests.php?request_id=' . $requestId;

        foreach ($admins as $adminId) {
            if ($adminId <= 0) {
                continue;
            }

            createNotification(
                $adminId,
                'Password reset requested',
                $message,
                'system',
                'password_reset_requests',
                $requestId,
                $actionUrl
            );
        }
    } catch (Throwable $e) {
        error_log('notifyAdminsAboutPasswordResetRequest error: ' . $e->getMessage());
    }
}

function getPasswordResetRequestById(int $requestId): ?array
{
    if ($requestId <= 0 || !ensurePasswordResetRequestsTable()) {
        return null;
    }

    try {
        $conn = getConnection();
        $passwordChangedAtSelect = dbColumnExists($conn, 'users', 'password_changed_at')
            ? ', u.password_changed_at'
            : '';
        $stmt = $conn->prepare(
            "SELECT pr.*, u.username, u.full_name, u.email, u.role, u.status AS user_status, u.password{$passwordChangedAtSelect},
                    admin.full_name AS processed_by_name
             FROM password_reset_requests pr
             INNER JOIN users u ON u.id = pr.user_id
             LEFT JOIN users admin ON admin.id = pr.processed_by
             WHERE pr.id = ?
             LIMIT 1"
        );
        if ($stmt === false) {
            return null;
        }

        $stmt->bind_param('i', $requestId);
        $stmt->execute();
        $result = $stmt->get_result();
        $request = $result ? ($result->fetch_assoc() ?: null) : null;
        $stmt->close();

        return $request;
    } catch (Throwable $e) {
        error_log('getPasswordResetRequestById error: ' . $e->getMessage());
        return null;
    }
}

function getPasswordResetRequests(?string $status = null): array
{
    if (!ensurePasswordResetRequestsTable()) {
        return [];
    }

    try {
        $conn = getConnection();
        $sql = "
            SELECT pr.*, u.username, u.full_name, u.email, u.role, u.status AS user_status,
                   admin.full_name AS processed_by_name
            FROM password_reset_requests pr
            INNER JOIN users u ON u.id = pr.user_id
            LEFT JOIN users admin ON admin.id = pr.processed_by
        ";

        $validStatus = trim((string) $status);
        if ($validStatus !== '') {
            $sql .= ' WHERE pr.status = ?';
        }

        $sql .= "
            ORDER BY
                CASE pr.status
                    WHEN 'pending' THEN 0
                    WHEN 'failed' THEN 1
                    WHEN 'sent' THEN 2
                    ELSE 3
                END,
                pr.requested_at DESC
        ";

        $stmt = $conn->prepare($sql);
        if ($stmt === false) {
            return [];
        }

        if ($validStatus !== '') {
            $stmt->bind_param('s', $validStatus);
        }

        $stmt->execute();
        $result = $stmt->get_result();
        $requests = [];
        if ($result) {
            while ($row = $result->fetch_assoc()) {
                $requests[] = $row;
            }
        }
        $stmt->close();

        return $requests;
    } catch (Throwable $e) {
        error_log('getPasswordResetRequests error: ' . $e->getMessage());
        return [];
    }
}

function getPasswordResetRequestCounts(): array
{
    if (!ensurePasswordResetRequestsTable()) {
        return ['total' => 0, 'pending' => 0, 'failed' => 0, 'sent' => 0, 'closed' => 0];
    }

    try {
        $conn = getConnection();
        $result = $conn->query("
            SELECT
                COUNT(*) AS total,
                SUM(CASE WHEN status = 'pending' THEN 1 ELSE 0 END) AS pending_count,
                SUM(CASE WHEN status = 'failed' THEN 1 ELSE 0 END) AS failed_count,
                SUM(CASE WHEN status = 'sent' THEN 1 ELSE 0 END) AS sent_count,
                SUM(CASE WHEN status = 'closed' THEN 1 ELSE 0 END) AS closed_count
            FROM password_reset_requests
        ");

        $row = $result ? ($result->fetch_assoc() ?: []) : [];

        return [
            'total' => (int) ($row['total'] ?? 0),
            'pending' => (int) ($row['pending_count'] ?? 0),
            'failed' => (int) ($row['failed_count'] ?? 0),
            'sent' => (int) ($row['sent_count'] ?? 0),
            'closed' => (int) ($row['closed_count'] ?? 0),
        ];
    } catch (Throwable $e) {
        error_log('getPasswordResetRequestCounts error: ' . $e->getMessage());
        return ['total' => 0, 'pending' => 0, 'failed' => 0, 'sent' => 0, 'closed' => 0];
    }
}

function generateTemporaryPassword(int $length = 12): string
{
    $alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!@#$%';
    $maxIndex = strlen($alphabet) - 1;
    $password = '';

    for ($i = 0; $i < $length; $i++) {
        $password .= $alphabet[random_int(0, $maxIndex)];
    }

    return $password;
}

function sendTemporaryPasswordForRequest(int $requestId, int $adminId, string $adminNote = ''): array
{
    $request = getPasswordResetRequestById($requestId);
    if (!$request) {
        return ['success' => false, 'error' => 'Password reset request not found.'];
    }

    if ($request['status'] === 'closed') {
        return ['success' => false, 'error' => 'This password reset request is already closed.'];
    }

    if (!isMailConfigured()) {
        return ['success' => false, 'error' => 'Gmail SMTP is not configured yet.'];
    }

    $email = trim((string) ($request['email'] ?? ''));
    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
        return ['success' => false, 'error' => 'The user does not have a valid email address.'];
    }

    $conn = getConnection();
    ensureUserPasswordSecurityColumns();
    $temporaryPassword = generateTemporaryPassword();
    $newPasswordHash = hashPassword($temporaryPassword);
    $previousPasswordHash = (string) ($request['password'] ?? '');
    $previousPasswordChangedAt = isset($request['password_changed_at']) && $request['password_changed_at'] !== ''
        ? (string) $request['password_changed_at']
        : null;

    try {
        $hasPasswordChangedAt = dbColumnExists($conn, 'users', 'password_changed_at');
        $updateSql = $hasPasswordChangedAt
            ? 'UPDATE users SET password = ?, password_changed_at = CURRENT_TIMESTAMP WHERE id = ?'
            : 'UPDATE users SET password = ? WHERE id = ?';
        $updatePasswordStmt = $conn->prepare($updateSql);
        if ($updatePasswordStmt === false) {
            return ['success' => false, 'error' => 'Failed to prepare the password update.'];
        }

        $updatePasswordStmt->bind_param('si', $newPasswordHash, $request['user_id']);
        $passwordUpdated = $updatePasswordStmt->execute();
        $updatePasswordStmt->close();

        if (!$passwordUpdated) {
            return ['success' => false, 'error' => 'Failed to update the user password.'];
        }

        $emailResult = sendTemporaryPasswordEmail($request, $temporaryPassword, $adminNote);
        if (!$emailResult['success']) {
            $rollbackSucceeded = rollbackTemporaryPassword(
                $request['user_id'],
                $previousPasswordHash,
                $hasPasswordChangedAt ? $previousPasswordChangedAt : null
            );
            updatePasswordResetRequestStatus(
                $requestId,
                'failed',
                $adminId,
                $adminNote,
                (string) ($emailResult['error'] ?? 'Unknown email error'),
                false
            );

            logActivity(
                $adminId,
                'admin_send_temporary_password_failed',
                'password_reset_requests',
                $requestId,
                ['user_id' => $request['user_id']],
                ['email' => $email, 'rollback_succeeded' => $rollbackSucceeded],
                'failed',
                (string) ($emailResult['error'] ?? 'Unknown email error')
            );

            return [
                'success' => false,
                'error' => $rollbackSucceeded
                    ? 'Email sending failed, so the password change was rolled back. ' . (string) ($emailResult['error'] ?? '')
                    : 'Email sending failed and the password rollback also failed. Please resolve this user manually immediately.',
            ];
        }

        updatePasswordResetRequestStatus($requestId, 'sent', $adminId, $adminNote, null, true);
        logActivity(
            $adminId,
            'admin_sent_temporary_password',
            'password_reset_requests',
            $requestId,
            ['user_id' => $request['user_id']],
            ['email' => $email],
            'success'
        );

        return ['success' => true, 'error' => null];
    } catch (Throwable $e) {
        error_log('sendTemporaryPasswordForRequest error: ' . $e->getMessage());
        return ['success' => false, 'error' => 'Unexpected error while sending the temporary password.'];
    }
}

function closePasswordResetRequest(int $requestId, int $adminId, string $adminNote = ''): array
{
    $request = getPasswordResetRequestById($requestId);
    if (!$request) {
        return ['success' => false, 'error' => 'Password reset request not found.'];
    }

    updatePasswordResetRequestStatus($requestId, 'closed', $adminId, $adminNote, null, false);
    logActivity(
        $adminId,
        'admin_closed_password_reset_request',
        'password_reset_requests',
        $requestId,
        ['user_id' => $request['user_id']],
        ['status' => 'closed'],
        'success'
    );

    return ['success' => true, 'error' => null];
}

