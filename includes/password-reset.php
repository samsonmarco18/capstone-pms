    if (trim($adminNote) !== '') {
        $textBody .= "\n\nAdmin note:\n" . trim($adminNote);
    }

    return sendSystemEmail($email, 'EVORTIX PMS Temporary Password', $htmlBody, $textBody);
}

function updatePasswordResetRequestStatus(
    int $requestId,
    string $status,
    int $adminId,
    string $adminNote,
    ?string $lastError,
    bool $passwordSent
): void {
    try {
        $conn = getConnection();
        $sql = "
            UPDATE password_reset_requests
            SET status = ?,
                admin_note = ?,
                last_error = ?,
                processed_by = ?,
                processed_at = CURRENT_TIMESTAMP,
                temp_password_sent_at = " . ($passwordSent ? 'CURRENT_TIMESTAMP' : 'temp_password_sent_at') . "
            WHERE id = ?
        ";
        $stmt = $conn->prepare($sql);
        if ($stmt === false) {
            return;
        }

        $trimmedNote = trim($adminNote);
        $stmt->bind_param('sssii', $status, $trimmedNote, $lastError, $adminId, $requestId);
        $stmt->execute();
        $stmt->close();
    } catch (Throwable $e) {
        error_log('updatePasswordResetRequestStatus error: ' . $e->getMessage());
    }
}

function rollbackTemporaryPassword(int $userId, string $previousPasswordHash, ?string $previousPasswordChangedAt = null): bool
{
    try {
        $conn = getConnection();
        $hasPasswordChangedAt = dbColumnExists($conn, 'users', 'password_changed_at');
        $sql = $hasPasswordChangedAt
            ? ($previousPasswordChangedAt === null || $previousPasswordChangedAt === ''
                ? 'UPDATE users SET password = ?, password_changed_at = NULL WHERE id = ?'
                : 'UPDATE users SET password = ?, password_changed_at = ? WHERE id = ?')
            : 'UPDATE users SET password = ? WHERE id = ?';
        $stmt = $conn->prepare($sql);
        if ($stmt === false) {
            return false;
        }

        if ($hasPasswordChangedAt) {
            if ($previousPasswordChangedAt === null || $previousPasswordChangedAt === '') {
                $stmt->bind_param('si', $previousPasswordHash, $userId);
            } else {
                $stmt->bind_param('ssi', $previousPasswordHash, $previousPasswordChangedAt, $userId);
            }
        } else {
            $stmt->bind_param('si', $previousPasswordHash, $userId);
        }

        $result = $stmt->execute();
        $stmt->close();

        return $result;
    } catch (Throwable $e) {
        error_log('rollbackTemporaryPassword error: ' . $e->getMessage());
        return false;
    }
}
