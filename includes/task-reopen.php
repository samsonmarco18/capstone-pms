function taskReopenEnsureSchema(mysqli|PgsqlMysqliCompatConnection $conn): void
{
    static $ensured = false;
    if ($ensured) {
        return;
    }

    $timestampType = DB_DRIVER === 'pgsql' ? 'TIMESTAMP' : 'DATETIME';
    $idType = DB_DRIVER === 'pgsql' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INT PRIMARY KEY AUTO_INCREMENT';
    $textType = DB_DRIVER === 'pgsql' ? 'TEXT' : 'TEXT';
    $statusDefault = "VARCHAR(40) NOT NULL DEFAULT 'pending_sul'";

    if (!dbTableExists($conn, 'task_reopen_requests')) {
        $conn->query("
            CREATE TABLE task_reopen_requests (
                id {$idType},
                task_id INT NOT NULL,
                project_id INT NOT NULL,
                requested_by INT NOT NULL,
                severity VARCHAR(20) NOT NULL DEFAULT 'minor',
                reason {$textType} NOT NULL,
                status {$statusDefault},
                sul_reviewed_by INT NULL,
                sul_reviewed_at {$timestampType} NULL,
                sul_comment {$textType} NULL,
                architect_reviewed_by INT NULL,
                architect_reviewed_at {$timestampType} NULL,
                architect_comment {$textType} NULL,
                reopened_scope VARCHAR(20) NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP" . (DB_DRIVER === 'pgsql' ? '' : ' ON UPDATE CURRENT_TIMESTAMP') . "
            )
        ");
    }

    $ensured = true;
}

function taskReopenActiveStatuses(): array
{
    return ['pending_sul', 'pending_architect'];
}

function taskReopenSeverityLabel(string $severity): string
{
    return strtolower(trim($severity)) === 'major' ? 'Major' : 'Minor';
}

function taskReopenHasActiveRequest(mysqli|PgsqlMysqliCompatConnection $conn, int $taskId): bool
{
    taskReopenEnsureSchema($conn);
    $statuses = implode(',', array_map(
        static fn(string $status): string => "'" . $conn->real_escape_string($status) . "'",
        taskReopenActiveStatuses()
    ));
    $result = $conn->query("
        SELECT id
        FROM task_reopen_requests
        WHERE task_id = {$taskId}
          AND status IN ({$statuses})
        LIMIT 1
    ");

    return $result && $result->num_rows > 0;
}

function taskReopenCreateRequest(
    mysqli|PgsqlMysqliCompatConnection $conn,
    int $taskId,
    int $developerId,
    string $severity,
    string $reason
): array {
    taskReopenEnsureSchema($conn);
    $severity = strtolower(trim($severity)) === 'major' ? 'major' : 'minor';
    $reason = trim($reason);

    if ($taskId <= 0 || $developerId <= 0 || $reason === '') {
        return ['success' => false, 'message' => 'Please select a task and provide a reopen reason.'];
    }

    $taskStmt = $conn->prepare("
        SELECT t.id, t.title, t.status, t.project_id, t.assigned_to, t.assigned_by,
               p.name AS project_name, p.sul_id
        FROM tasks t
        JOIN projects p ON p.id = t.project_id
        WHERE t.id = ? AND t.assigned_to = ?
        LIMIT 1
    ");
    if (!$taskStmt) {
        return ['success' => false, 'message' => 'Unable to validate the task.'];
    }
    $taskStmt->bind_param('ii', $taskId, $developerId);
    $taskStmt->execute();
    $task = $taskStmt->get_result()->fetch_assoc();
    $taskStmt->close();

    if (!$task) {
        return ['success' => false, 'message' => 'You can only request reopen for tasks assigned to you.'];
    }

    $allowedStatuses = ['for_review', 'qa_testing', 'qa_failed', 'qa_passed', 'architect_review', 'merged', 'ready_for_release', 'completed'];
    if (!in_array((string) ($task['status'] ?? ''), $allowedStatuses, true)) {
        return ['success' => false, 'message' => 'Reopen requests are only available after a task has entered review, QA, final approval, or completion.'];
    }

    if (taskReopenHasActiveRequest($conn, $taskId)) {
        return ['success' => false, 'message' => 'This task already has a pending reopen request.'];
    }

    $projectId = (int) ($task['project_id'] ?? 0);
    $stmt = $conn->prepare("
        INSERT INTO task_reopen_requests (task_id, project_id, requested_by, severity, reason)
        VALUES (?, ?, ?, ?, ?)
    ");
    if (!$stmt) {
        return ['success' => false, 'message' => 'Unable to create the reopen request.'];
    }
    $stmt->bind_param('iiiss', $taskId, $projectId, $developerId, $severity, $reason);
    $ok = $stmt->execute();
    $requestId = (int) $stmt->insert_id;
    $stmt->close();

    if (!$ok) {
        return ['success' => false, 'message' => 'Failed to save the reopen request.'];
    }

    workflowAddTaskComment(
        $conn,
        $taskId,
        $developerId,
        'Developer requested reopen (' . taskReopenSeverityLabel($severity) . '): ' . $reason
    );
    logActivity($developerId, 'developer_request_task_reopen', 'task_reopen_requests', $requestId, null, [
        'task_id' => $taskId,
        'project_id' => $projectId,
        'severity' => $severity,
        'reason' => $reason,
    ]);

    $recipientIds = array_unique(array_filter([
        (int) ($task['sul_id'] ?? 0),
        (int) ($task['assigned_by'] ?? 0),
    ]));
    foreach ($recipientIds as $recipientId) {
        workflowNotifyUser(
            $recipientId,
            'Task Reopen Requested: ' . (string) ($task['title'] ?? 'Task'),
            'Developer requested a ' . taskReopenSeverityLabel($severity) . ' reopen. Reason: ' . $reason,
            BASE_URL . 'modules/sul/task-allocation.php?task_id=' . $taskId,
            $taskId
        );
    }
    $taskDepartment = projectWorkflowTaskDepartment($conn, $taskId);
    if ($taskDepartment !== '') {
        projectWorkflowNotifyDepartmentSuls(
            $conn,
            $taskDepartment,
            'Task Reopen Requested: ' . (string) ($task['title'] ?? 'Task'),
            'A developer requested SUL review for a ' . taskReopenSeverityLabel($severity) . ' reopen.',
            BASE_URL . 'modules/sul/task-allocation.php?project_id=' . $projectId . '#developer-reopen-panel',
            $projectId
        );
    } else {
        workflowNotifyRoles(
            $conn,
            ['sul'],
            'Task Reopen Requested: ' . (string) ($task['title'] ?? 'Task'),
            'A developer requested SUL review for a ' . taskReopenSeverityLabel($severity) . ' reopen.',
            BASE_URL . 'modules/sul/task-allocation.php?task_id=' . $taskId,
            $taskId,
            'approval',
            'tasks'
        );
    }

    return ['success' => true, 'message' => 'Reopen request sent to SUL.', 'request_id' => $requestId];
}

function taskReopenLoadSulRequests(mysqli|PgsqlMysqliCompatConnection $conn, string $department, int $projectId = 0): array
{
    taskReopenEnsureSchema($conn);
    $projectFilter = projectWorkflowProjectDepartmentClause($conn, 'p', $department);
    $selectedFilter = $projectId > 0 ? ' AND r.project_id = ' . $projectId : '';
    $rows = [];
    $result = $conn->query("
        SELECT r.*, t.title AS task_title, t.status AS task_status, p.name AS project_name,
               requester.full_name AS requester_name, dev.full_name AS developer_name
        FROM task_reopen_requests r
        JOIN tasks t ON t.id = r.task_id
        JOIN projects p ON p.id = r.project_id
        JOIN users requester ON requester.id = r.requested_by
        LEFT JOIN users dev ON dev.id = t.assigned_to
        WHERE r.status = 'pending_sul'
          AND {$projectFilter}
          {$selectedFilter}
        ORDER BY r.created_at ASC, r.id ASC
    ");
    if ($result) {
        while ($row = $result->fetch_assoc()) {
            $rows[] = $row;
        }
    }

    return $rows;
}

function taskReopenLoadArchitectRequests(mysqli|PgsqlMysqliCompatConnection $conn): array
{
    taskReopenEnsureSchema($conn);
    $rows = [];
    $result = $conn->query("
        SELECT r.*, t.title AS task_title, t.status AS task_status, p.name AS project_name,
               requester.full_name AS requester_name, sul.full_name AS sul_name
        FROM task_reopen_requests r
        JOIN tasks t ON t.id = r.task_id
        JOIN projects p ON p.id = r.project_id
        JOIN users requester ON requester.id = r.requested_by
        LEFT JOIN users sul ON sul.id = r.sul_reviewed_by
        WHERE r.status = 'pending_architect'
        ORDER BY r.sul_reviewed_at ASC, r.id ASC
    ");
    if ($result) {
        while ($row = $result->fetch_assoc()) {
            $rows[] = $row;
        }
    }

    return $rows;
}

function taskReopenSulDecision(
    mysqli|PgsqlMysqliCompatConnection $conn,
    int $requestId,
    int $sulId,
    string $decision,
    string $comment,
    string $department = ''
): array {
    taskReopenEnsureSchema($conn);
    $departmentFilter = $department !== ''
        ? ' AND ' . projectWorkflowProjectDepartmentClause($conn, 'p', $department)
        : '';
    $request = $conn->query("
        SELECT r.*, t.title AS task_title, t.assigned_to, p.name AS project_name
        FROM task_reopen_requests r
        JOIN tasks t ON t.id = r.task_id
        JOIN projects p ON p.id = r.project_id
        WHERE r.id = {$requestId} AND r.status = 'pending_sul'
          {$departmentFilter}
        LIMIT 1
    ")->fetch_assoc();
    if (!$request) {
        return ['success' => false, 'message' => 'Pending reopen request was not found.'];
    }

    $isApprove = $decision === 'approve';
    $newStatus = $isApprove ? 'pending_architect' : 'sul_rejected';
    $stmt = $conn->prepare("
        UPDATE task_reopen_requests
        SET status = ?, sul_reviewed_by = ?, sul_reviewed_at = NOW(), sul_comment = ?
        WHERE id = ? AND status = 'pending_sul'
    ");
    if (!$stmt) {
        return ['success' => false, 'message' => 'Unable to save SUL decision.'];
    }
    $stmt->bind_param('sisi', $newStatus, $sulId, $comment, $requestId);
    $ok = $stmt->execute();
    $stmt->close();
    if (!$ok) {
        return ['success' => false, 'message' => 'Failed to save SUL decision.'];
    }

    $taskId = (int) ($request['task_id'] ?? 0);
    $label = $isApprove ? 'SUL accepted reopen request' : 'SUL rejected reopen request';
    workflowAddTaskComment($conn, $taskId, $sulId, $label . ($comment !== '' ? ': ' . $comment : '.'));
    logActivity($sulId, $isApprove ? 'sul_accept_task_reopen_request' : 'sul_reject_task_reopen_request', 'task_reopen_requests', $requestId, null, [
        'task_id' => $taskId,
        'decision' => $decision,
        'comment' => $comment,
    ]);

    if ($isApprove) {
        workflowNotifyRoles(
            $conn,
            ['architect'],
            'Architect Reopen Review Needed: ' . (string) ($request['task_title'] ?? 'Task'),
            'SUL accepted a ' . taskReopenSeverityLabel((string) $request['severity']) . ' reopen request and sent it for Architect decision.',
            BASE_URL . 'modules/architect/final-approval.php?reopen_request_id=' . $requestId,
            $taskId,
            'approval',
            'tasks'
        );
    } else {
        workflowNotifyUser(
            (int) ($request['requested_by'] ?? 0),
            'Task Reopen Request Rejected: ' . (string) ($request['task_title'] ?? 'Task'),
            'SUL rejected the reopen request' . ($comment !== '' ? ': ' . $comment : '.'),
            BASE_URL . 'modules/developer/task.php?id=' . $taskId,
            $taskId
        );
    }

    return ['success' => true, 'message' => $isApprove ? 'Request sent to Architect.' : 'Request rejected.'];
}

function taskReopenApplyArchitectApproval(
    mysqli|PgsqlMysqliCompatConnection $conn,
    array $request,
    int $architectId,
    string $comment
): void {
    $taskId = (int) ($request['task_id'] ?? 0);
    $projectId = (int) ($request['project_id'] ?? 0);
    $severity = strtolower((string) ($request['severity'] ?? 'minor')) === 'major' ? 'major' : 'minor';

    $taskRow = $conn->query("SELECT status FROM tasks WHERE id = {$taskId} LIMIT 1")->fetch_assoc() ?: [];
    $oldStatus = (string) ($taskRow['status'] ?? 'completed');

    $resetTaskSql = "
        UPDATE tasks
        SET status = 'sul_revision',
            completed_at = NULL,
            qa_reviewed_by = NULL,
            qa_reviewed_at = NULL,
            architect_reviewed_by = NULL,
            architect_reviewed_at = NULL,
            merged_at = NULL,
            release_notified_at = NULL,
            pr_submitted_at = NULL
        WHERE id = {$taskId}
    ";
    $conn->query($resetTaskSql);
    workflowLogStatusChange($architectId, $taskId, $oldStatus, 'sul_revision', 'architect_approve_task_reopen', $comment);

    if ($severity === 'major') {
        $phase = $conn->query("
            SELECT mp.id, COALESCE(NULLIF(mp.sequence_no, 0), mp.id) AS phase_order
            FROM methodology_tasks mt
            JOIN methodology_phases mp ON mp.id = mt.phase_id
            WHERE mt.project_id = {$projectId}
              AND mt.task_id = {$taskId}
            ORDER BY COALESCE(NULLIF(mp.sequence_no, 0), mp.id) ASC, mt.start_date ASC, mt.id ASC
            LIMIT 1
        ")->fetch_assoc();

        if ($phase) {
            $phaseOrder = (int) ($phase['phase_order'] ?? 0);
            $phaseRows = $conn->query("
                SELECT id, COALESCE(NULLIF(sequence_no, 0), id) AS phase_order
                FROM methodology_phases
                WHERE project_id = {$projectId}
                  AND COALESCE(NULLIF(sequence_no, 0), id) >= {$phaseOrder}
            ");
            $phaseIds = [];
            if ($phaseRows) {
                while ($phaseRow = $phaseRows->fetch_assoc()) {
                    $phaseIds[] = (int) ($phaseRow['id'] ?? 0);
                }
            }
            $phaseIds = array_values(array_filter(array_unique($phaseIds)));

            if ($phaseIds) {
                $phaseIdList = implode(',', $phaseIds);
                $conn->query("
                    UPDATE methodology_phases
                    SET status = CASE WHEN id = " . (int) $phase['id'] . " THEN 'in_progress' ELSE 'planned' END,
                        updated_by = {$architectId},
                        updated_at = CURRENT_TIMESTAMP
                    WHERE id IN ({$phaseIdList})
                ");

                $methodologyTaskRows = $conn->query("
                    SELECT id, task_id
                    FROM methodology_tasks
                    WHERE project_id = {$projectId}
                      AND phase_id IN ({$phaseIdList})
                ");
                $methodologyTaskIds = [];
                $downstreamWorkflowTaskIds = [];
                if ($methodologyTaskRows) {
                    while ($row = $methodologyTaskRows->fetch_assoc()) {
                        $methodologyTaskIds[] = (int) ($row['id'] ?? 0);
                        $linkedTaskId = (int) ($row['task_id'] ?? 0);
                        if ($linkedTaskId > 0 && $linkedTaskId !== $taskId) {
                            $downstreamWorkflowTaskIds[] = $linkedTaskId;
                        }
                    }
                }

                $methodologyTaskIds = array_values(array_filter(array_unique($methodologyTaskIds)));
                if ($methodologyTaskIds) {
                    $methodologyTaskIdList = implode(',', $methodologyTaskIds);
                    $conn->query("
                        UPDATE methodology_tasks
                        SET status = 'planned',
                            updated_by = {$architectId},
                            updated_at = CURRENT_TIMESTAMP
                        WHERE id IN ({$methodologyTaskIdList})
                    ");

                    if (dbTableExists($conn, 'methodology_task_departments')) {
                        $conn->query("
                            UPDATE methodology_task_departments
                            SET status = 'planned',
                                submitted_at = NULL,
                                approved_by = NULL,
                                approved_at = NULL,
                                revision_notes = NULL,
                                updated_by = {$architectId},
                                updated_at = CURRENT_TIMESTAMP
                            WHERE project_id = {$projectId}
                              AND methodology_task_id IN ({$methodologyTaskIdList})
                        ");
                    }
                }

                $downstreamWorkflowTaskIds = array_values(array_filter(array_unique($downstreamWorkflowTaskIds)));
                if ($downstreamWorkflowTaskIds) {
                    $conn->query("
                        UPDATE tasks
                        SET status = 'todo',
                            completed_at = NULL,
                            qa_reviewed_by = NULL,
                            qa_reviewed_at = NULL,
                            architect_reviewed_by = NULL,
                            architect_reviewed_at = NULL,
                            merged_at = NULL,
                            release_notified_at = NULL,
                            pr_submitted_at = NULL
                        WHERE id IN (" . implode(',', $downstreamWorkflowTaskIds) . ")
                    ");
                }
            }
        }
    }

    $conn->query("UPDATE projects SET status = 'in_progress' WHERE id = {$projectId} AND status = 'completed'");
    projectWorkflowSyncRoadmap($conn, $projectId);
}

function taskReopenArchitectDecision(
    mysqli|PgsqlMysqliCompatConnection $conn,
    int $requestId,
    int $architectId,
    string $decision,
    string $comment
): array {
    taskReopenEnsureSchema($conn);
    $request = $conn->query("
        SELECT r.*, t.title AS task_title, t.assigned_to, p.name AS project_name
        FROM task_reopen_requests r
        JOIN tasks t ON t.id = r.task_id
        JOIN projects p ON p.id = r.project_id
        WHERE r.id = {$requestId} AND r.status = 'pending_architect'
        LIMIT 1
    ")->fetch_assoc();
    if (!$request) {
        return ['success' => false, 'message' => 'Pending Architect reopen request was not found.'];
    }

    $isApprove = $decision === 'approve';
    $newStatus = $isApprove ? 'architect_approved' : 'architect_rejected';
    $scope = $isApprove ? (strtolower((string) $request['severity']) === 'major' ? 'phase' : 'task') : null;

    $stmt = $conn->prepare("
        UPDATE task_reopen_requests
        SET status = ?, architect_reviewed_by = ?, architect_reviewed_at = NOW(), architect_comment = ?, reopened_scope = ?
        WHERE id = ? AND status = 'pending_architect'
    ");
    if (!$stmt) {
        return ['success' => false, 'message' => 'Unable to save Architect decision.'];
    }
    $stmt->bind_param('sissi', $newStatus, $architectId, $comment, $scope, $requestId);
    $ok = $stmt->execute();
    $stmt->close();
    if (!$ok) {
        return ['success' => false, 'message' => 'Failed to save Architect decision.'];
    }

    $taskId = (int) ($request['task_id'] ?? 0);
    if ($isApprove) {
        taskReopenApplyArchitectApproval($conn, $request, $architectId, $comment);
    }

    workflowAddTaskComment(
        $conn,
        $taskId,
        $architectId,
        ($isApprove ? 'Architect approved reopen' : 'Architect rejected reopen') . ($comment !== '' ? ': ' . $comment : '.')
    );
    logActivity($architectId, $isApprove ? 'architect_approve_task_reopen' : 'architect_reject_task_reopen', 'task_reopen_requests', $requestId, null, [
        'task_id' => $taskId,
        'severity' => $request['severity'] ?? 'minor',
        'scope' => $scope,
        'comment' => $comment,
    ]);

    $developerId = (int) ($request['requested_by'] ?? 0);
    workflowNotifyUser(
        $developerId,
        ($isApprove ? 'Task Reopened: ' : 'Task Reopen Rejected: ') . (string) ($request['task_title'] ?? 'Task'),
        $isApprove
            ? 'Architect reopened the task' . ($scope === 'phase' ? ' and downstream phases.' : '.') . ' You can now make the requested changes.'
            : 'Architect rejected the reopen request' . ($comment !== '' ? ': ' . $comment : '.'),
        BASE_URL . 'modules/developer/task.php?id=' . $taskId,
        $taskId
    );

    return ['success' => true, 'message' => $isApprove ? 'Task reopen approved.' : 'Task reopen rejected.'];
}
