const PROJECT_ESTIMATION_SALARIES = [
    'Junior Dev' => 25000.0,
    'Professional Dev' => 60000.0,
    'Senior Dev' => 80000.0,
];

function projectEstimationDeveloperLevel(string $value): string
{
    $normalized = strtolower(trim($value));

    return match ($normalized) {
        'junior developer', 'junior dev', 'junior' => 'Junior Dev',
        'professional developer', 'professional dev', 'professional', 'mid developer', 'mid dev', 'mid-level developer' => 'Professional Dev',
        'senior developer', 'senior dev', 'senior' => 'Senior Dev',
        default => isset(PROJECT_ESTIMATION_SALARIES[$value]) ? $value : 'Professional Dev',
    };
}

function projectEstimationEnsureSchema(mysqli|PgsqlMysqliCompatConnection $conn): void
{
    if (dbTableExists($conn, 'expert_project_estimations')) {
        return;
    }

    $jsonType = DB_DRIVER === 'pgsql' ? 'TEXT' : 'LONGTEXT';
    $statusType = DB_DRIVER === 'pgsql'
        ? "VARCHAR(40) DEFAULT 'draft'"
        : "ENUM('draft','submitted','sul_rejected','sul_approved','sales_rejected','sales_approved') DEFAULT 'draft'";
    $dateType = DB_DRIVER === 'pgsql' ? 'TIMESTAMP' : 'DATETIME';
    $idType = DB_DRIVER === 'pgsql' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INT PRIMARY KEY AUTO_INCREMENT';
    $uniqueSql = DB_DRIVER === 'pgsql' ? 'UNIQUE (project_id)' : 'UNIQUE KEY unique_project_estimation (project_id)';

    $conn->query("
        CREATE TABLE expert_project_estimations (
            id {$idType},
            project_id INT NOT NULL,
            expert_id INT NOT NULL,
            status {$statusType},
            project_duration_months INT DEFAULT 1,
            project_complexity VARCHAR(40) DEFAULT 'Medium',
            allocation_json {$jsonType} NULL,
            additional_costs DECIMAL(15, 2) DEFAULT 0,
            total_developer_cost DECIMAL(15, 2) DEFAULT 0,
            total_technology_stack_cost DECIMAL(15, 2) DEFAULT 0,
            overall_estimated_project_cost DECIMAL(15, 2) DEFAULT 0,
            remaining_budget DECIMAL(15, 2) DEFAULT 0,
            sul_reviewed_by INT NULL,
            sul_reviewed_at {$dateType} NULL,
            sul_comment TEXT NULL,
            sales_reviewed_by INT NULL,
            sales_reviewed_at {$dateType} NULL,
            sales_comment TEXT NULL,
            submitted_at {$dateType} NULL,
            approved_at {$dateType} NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP" . (DB_DRIVER === 'pgsql' ? '' : ' ON UPDATE CURRENT_TIMESTAMP') . ",
            {$uniqueSql}
        )
    ");
}

function projectEstimationPeso(float|int|null $amount): string
{
    return '&#8369;' . number_format((float) $amount, 2);
}

function projectEstimationMonths(?string $start, ?string $end): int
{
    $startDate = $start ? DateTime::createFromFormat('Y-m-d', substr($start, 0, 10)) : false;
    $endDate = $end ? DateTime::createFromFormat('Y-m-d', substr($end, 0, 10)) : false;
    if (!$startDate || !$endDate || $endDate < $startDate) {
        return 1;
    }

    $days = max(1, (int) $startDate->diff($endDate)->format('%a') + 1);
    return max(1, (int) ceil($days / 30));
}

function projectEstimationDepartmentLabel(string $department): string
{
    $value = trim($department);
    $normalized = strtolower($value);
    return match ($normalized) {
        'ui/ux designer', 'ui ux designer', 'ui/ux' => 'UI/UX',
        'frontend developer', 'frontend' => 'Frontend',
        'backend developer', 'backend' => 'Backend',
        'full stack developer', 'fullstack developer', 'full stack' => 'Frontend',
        'mobile developer', 'mobile' => 'Mobile',
        'devops engineer', 'devops' => 'DevOps',
        'database administrator', 'database' => 'Database',
        'ai engineer', 'ai' => 'AI',
        'security engineer', 'security' => 'Security',
        'qa engineer', 'qa' => 'QA',
        'expert department' => 'Expert Department',
        'other departments', 'other' => 'Other Departments',
        default => $value !== '' ? $value : 'Other Departments',
    };
}

function projectEstimationComplexity(int $durationMonths, int $headcount, int $techCount): string
{
    $score = 0;
    $score += $durationMonths >= 12 ? 3 : ($durationMonths >= 6 ? 2 : 1);
    $score += $headcount >= 10 ? 3 : ($headcount >= 5 ? 2 : 1);
    $score += $techCount >= 8 ? 3 : ($techCount >= 4 ? 2 : 1);

    return match (true) {
        $score >= 8 => 'Critical',
        $score >= 6 => 'High',
        $score >= 4 => 'Medium',
        default => 'Low',
    };
}

function projectEstimationFetchProjects(mysqli|PgsqlMysqliCompatConnection $conn, int $expertId): array
{
    $rows = [];
    $result = $conn->query("
        SELECT DISTINCT p.*, c.name AS client_name, e.status AS estimation_status
        FROM projects p
        JOIN clients c ON c.id = p.client_id
        LEFT JOIN tasks t ON t.project_id = p.id AND t.assigned_to = {$expertId}
        LEFT JOIN expert_project_estimations e ON e.project_id = p.id
        WHERE (t.id IS NOT NULL OR e.expert_id = {$expertId})
          AND p.status != 'completed'
        ORDER BY p.created_at DESC, p.name ASC
    ");
    if ($result) {
        while ($row = $result->fetch_assoc()) {
            $rows[] = $row;
        }
    }

    return $rows;
}

function projectEstimationFetchContext(mysqli|PgsqlMysqliCompatConnection $conn, int $projectId): array
{
    $project = $conn->query("
        SELECT p.*, c.name AS client_name
        FROM projects p
        JOIN clients c ON c.id = p.client_id
        WHERE p.id = {$projectId}
        LIMIT 1
    ")->fetch_assoc() ?: null;

    if (!$project) {
        return [];
    }

    $techRows = [];
    $techResult = $conn->query("
        SELECT tr.*, t.name AS technology_name
        FROM tech_recommendations tr
        JOIN technologies t ON t.id = tr.tech_id
        WHERE tr.project_id = {$projectId}
        ORDER BY t.name ASC
    ");
    if ($techResult) {
        while ($row = $techResult->fetch_assoc()) {
            $techRows[] = $row;
        }
    }

    $allocationRows = [];
    if (dbTableExists($conn, 'methodology_task_departments')) {
        $roadmapRequirementResult = $conn->query("
            SELECT department, SUM(required_count) AS required_count
            FROM methodology_task_departments
            WHERE project_id = {$projectId}
            GROUP BY department
            ORDER BY department ASC
        ");
        if ($roadmapRequirementResult) {
            while ($row = $roadmapRequirementResult->fetch_assoc()) {
                $label = projectEstimationDepartmentLabel((string) ($row['department'] ?? ''));
                $allocationRows[$label] = [
                    'department' => $label,
                    'required_count' => max(0, (int) ($row['required_count'] ?? 0)),
                    'complexity_level' => 'medium',
                    'source' => 'roadmap',
                ];
            }
        }
    }

    if ($allocationRows === [] && dbTableExists($conn, 'methodology_tasks')) {
        $roadmapTaskResult = $conn->query("
            SELECT department, COUNT(*) AS required_count
            FROM methodology_tasks
            WHERE project_id = {$projectId}
              AND COALESCE(department, '') != ''
            GROUP BY department
            ORDER BY department ASC
        ");
        if ($roadmapTaskResult) {
            while ($row = $roadmapTaskResult->fetch_assoc()) {
                $label = projectEstimationDepartmentLabel((string) ($row['department'] ?? ''));
                $allocationRows[$label] = [
                    'department' => $label,
                    'required_count' => max(0, (int) ($row['required_count'] ?? 0)),
                    'complexity_level' => 'medium',
                    'source' => 'roadmap',
                ];
            }
        }
    }

    if (dbTableExists($conn, 'developer_allocations')) {
        $allocResult = $conn->query("
            SELECT role, required_count, complexity_level
            FROM developer_allocations
            WHERE project_id = {$projectId}
            ORDER BY FIELD(role, 'UI/UX', 'Frontend', 'Backend', 'Mobile', 'DevOps', 'Database', 'AI', 'Security', 'QA', 'Other Departments'), role ASC
        ");
        if ($allocResult) {
            while ($row = $allocResult->fetch_assoc()) {
                $label = projectEstimationDepartmentLabel((string) ($row['role'] ?? ''));
                if (isset($allocationRows[$label]) && (int) ($allocationRows[$label]['required_count'] ?? 0) > 0) {
                    continue;
                }
                $allocationRows[$label] = [
                    'department' => $label,
                    'required_count' => (int) ($row['required_count'] ?? 0),
                    'complexity_level' => (string) ($row['complexity_level'] ?? 'medium'),
                    'source' => 'developer_allocation',
                ];
            }
        }
    }

    $includedRaw = trim((string) ($project['included_departments'] ?? ''));
    if ($includedRaw !== '') {
        $included = json_decode($includedRaw, true);
        if (is_array($included)) {
            foreach ($included as $department) {
                $label = projectEstimationDepartmentLabel((string) $department);
                if (!isset($allocationRows[$label])) {
                    $allocationRows[$label] = [
                        'department' => $label,
                        'required_count' => 0,
                        'complexity_level' => 'medium',
                    ];
                }
            }
        }
    }

    $estimation = $conn->query("
        SELECT *
        FROM expert_project_estimations
        WHERE project_id = {$projectId}
        LIMIT 1
    ")->fetch_assoc() ?: null;

    return [
        'project' => $project,
        'technologies' => $techRows,
        'allocations' => array_values($allocationRows),
        'estimation' => $estimation,
    ];
}

function projectEstimationNormalizeRows(array $postedAllocations, array $allocationRows): array
{
    $normalized = [];
    $allocationLookup = [];
    foreach ($allocationRows as $allocation) {
        $allocationLookup[(string) $allocation['department']] = max(0, (int) $allocation['required_count']);
    }

    foreach ($postedAllocations as $department => $positions) {
        $departmentLabel = projectEstimationDepartmentLabel((string) $department);
        $required = $allocationLookup[$departmentLabel] ?? 0;
        if ($required <= 0 || !is_array($positions)) {
            continue;
        }

        for ($i = 1; $i <= $required; $i++) {
            $entry = is_array($positions[$i] ?? null) ? $positions[$i] : [];
            $developerType = (string) ($entry['developer_type'] ?? 'Professional Dev');
            $developerType = projectEstimationDeveloperLevel($developerType);

            $contribution = max(0.0, min(100.0, (float) ($entry['contribution'] ?? 100)));
            $monthlySalary = PROJECT_ESTIMATION_SALARIES[$developerType];
            $salaryContribution = $monthlySalary * ($contribution / 100);

            $normalized[] = [
                'department' => $departmentLabel,
                'position' => $i,
                'developer_type' => $developerType,
                'monthly_salary' => $monthlySalary,
                'contribution_percent' => $contribution,
                'salary_based_on_contribution' => $salaryContribution,
                'developers_needed' => 1,
                'total_cost_based_on_developers' => $salaryContribution,
            ];
        }
    }

    return $normalized;
}

function projectEstimationSave(
    mysqli|PgsqlMysqliCompatConnection $conn,
    int $projectId,
    int $expertId,
    array $allocationRows,
    int $durationMonths,
    float $techMonthlyCost,
    float $additionalCosts,
    string $complexity,
    array $postedAllocations
): bool {
    $rows = projectEstimationNormalizeRows($postedAllocations, $allocationRows);
    $developerMonthlyCost = array_sum(array_map(static fn(array $row): float => (float) $row['total_cost_based_on_developers'], $rows));
    $developerCost = $developerMonthlyCost * $durationMonths;
    $technologyCost = $techMonthlyCost * $durationMonths;
    $overallCost = $developerCost + $technologyCost + $additionalCosts;

    $project = $conn->query("SELECT sales_budget FROM projects WHERE id = {$projectId} LIMIT 1")->fetch_assoc() ?: [];
    $budget = (float) ($project['sales_budget'] ?? 0);
    $remaining = $budget - $overallCost;
    $allocationJson = json_encode($rows, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    $existing = $conn->query("SELECT id FROM expert_project_estimations WHERE project_id = {$projectId} LIMIT 1")->fetch_assoc();

    if ($existing) {
        $stmt = $conn->prepare("
            UPDATE expert_project_estimations
            SET expert_id = ?, status = 'submitted', project_duration_months = ?, project_complexity = ?,
                allocation_json = ?, additional_costs = ?, total_developer_cost = ?,
                total_technology_stack_cost = ?, overall_estimated_project_cost = ?, remaining_budget = ?,
                sul_reviewed_by = NULL, sul_reviewed_at = NULL, sul_comment = NULL,
                sales_reviewed_by = NULL, sales_reviewed_at = NULL, sales_comment = NULL,
                submitted_at = NOW()
            WHERE project_id = ?
        ");
        $stmt->bind_param('iissdddddi', $expertId, $durationMonths, $complexity, $allocationJson, $additionalCosts, $developerCost, $technologyCost, $overallCost, $remaining, $projectId);
    } else {
        $stmt = $conn->prepare("
            INSERT INTO expert_project_estimations (
                project_id, expert_id, status, project_duration_months, project_complexity, allocation_json,
                additional_costs, total_developer_cost, total_technology_stack_cost,
                overall_estimated_project_cost, remaining_budget, submitted_at
            ) VALUES (?, ?, 'submitted', ?, ?, ?, ?, ?, ?, ?, ?, NOW())
        ");
        $stmt->bind_param('iiissddddd', $projectId, $expertId, $durationMonths, $complexity, $allocationJson, $additionalCosts, $developerCost, $technologyCost, $overallCost, $remaining);
    }

    $ok = $stmt->execute();
    $stmt->close();
    return $ok;
}

function projectEstimationCompletePlanningPhase(mysqli|PgsqlMysqliCompatConnection $conn, int $projectId, int $userId): void
{
    $phase = $conn->query("
        SELECT id
        FROM methodology_phases
        WHERE project_id = {$projectId}
          AND LOWER(name) LIKE '%planning%'
        ORDER BY sequence_no ASC, id ASC
        LIMIT 1
    ")->fetch_assoc();

    if (!$phase) {
        $phase = $conn->query("
            SELECT id
            FROM methodology_phases
            WHERE project_id = {$projectId}
            ORDER BY sequence_no ASC, id ASC
            LIMIT 1
        ")->fetch_assoc();
    }

    if (!$phase) {
        return;
    }

    $phaseId = (int) $phase['id'];
    $conn->query("UPDATE methodology_phases SET status = 'completed', updated_by = {$userId} WHERE id = {$phaseId}");
    $conn->query("UPDATE methodology_tasks SET status = 'completed', updated_by = {$userId} WHERE phase_id = {$phaseId}");

    $nextPhase = $conn->query("
        SELECT id
        FROM methodology_phases
        WHERE project_id = {$projectId}
          AND id != {$phaseId}
          AND status = 'planned'
        ORDER BY sequence_no ASC, id ASC
        LIMIT 1
    ")->fetch_assoc();
    if ($nextPhase) {
        $conn->query("UPDATE methodology_phases SET status = 'in_progress', updated_by = {$userId} WHERE id = " . (int) $nextPhase['id']);
    }
}

