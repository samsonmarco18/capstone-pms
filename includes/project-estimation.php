const PROJECT_ESTIMATION_SALARIES = [
    'Junior Dev' => 25000.0,
    'Professional Dev' => 60000.0,
    'Senior Dev' => 80000.0,
];

function projectEstimationDeveloperLevel(string $value): string
{
    $normalized = strtolower(trim($value));

    return match ($normalized) {
        'junior developer', 'junior dev', 'junior' => 'Junior Dev',
        'professional developer', 'professional dev', 'professional', 'mid developer', 'mid dev', 'mid-level developer' => 'Professional Dev',
        'senior developer', 'senior dev', 'senior' => 'Senior Dev',
        default => isset(PROJECT_ESTIMATION_SALARIES[$value]) ? $value : 'Professional Dev',
    };
}

function projectEstimationEnsureSchema(mysqli|PgsqlMysqliCompatConnection $conn): void
{
    if (dbTableExists($conn, 'expert_project_estimations')) {
        return;
    }

    $jsonType = DB_DRIVER === 'pgsql' ? 'TEXT' : 'LONGTEXT';
    $statusType = DB_DRIVER === 'pgsql'
        ? "VARCHAR(40) DEFAULT 'draft'"
        : "ENUM('draft','submitted','sul_rejected','sul_approved','sales_rejected','sales_approved') DEFAULT 'draft'";
    $dateType = DB_DRIVER === 'pgsql' ? 'TIMESTAMP' : 'DATETIME';
    $idType = DB_DRIVER === 'pgsql' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INT PRIMARY KEY AUTO_INCREMENT';
    $uniqueSql = DB_DRIVER === 'pgsql' ? 'UNIQUE (project_id)' : 'UNIQUE KEY unique_project_estimation (project_id)';

    $conn->query("
        CREATE TABLE expert_project_estimations (
            id {$idType},
            project_id INT NOT NULL,
            expert_id INT NOT NULL,
            status {$statusType},
            project_duration_months INT DEFAULT 1,
            project_complexity VARCHAR(40) DEFAULT 'Medium',
            allocation_json {$jsonType} NULL,
            additional_costs DECIMAL(15, 2) DEFAULT 0,
            total_developer_cost DECIMAL(15, 2) DEFAULT 0,
            total_technology_stack_cost DECIMAL(15, 2) DEFAULT 0,
            overall_estimated_project_cost DECIMAL(15, 2) DEFAULT 0,
            remaining_budget DECIMAL(15, 2) DEFAULT 0,
            sul_reviewed_by INT NULL,
            sul_reviewed_at {$dateType} NULL,
            sul_comment TEXT NULL,
            sales_reviewed_by INT NULL,
            sales_reviewed_at {$dateType} NULL,
            sales_comment TEXT NULL,
            submitted_at {$dateType} NULL,
            approved_at {$dateType} NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP" . (DB_DRIVER === 'pgsql' ? '' : ' ON UPDATE CURRENT_TIMESTAMP') . ",
            {$uniqueSql}
        )
    ");
}

function projectEstimationPeso(float|int|null $amount): string
{
    return '&#8369;' . number_format((float) $amount, 2);
}

function projectEstimationMonths(?string $start, ?string $end): int
{
    $startDate = $start ? DateTime::createFromFormat('Y-m-d', substr($start, 0, 10)) : false;
    $endDate = $end ? DateTime::createFromFormat('Y-m-d', substr($end, 0, 10)) : false;
    if (!$startDate || !$endDate || $endDate < $startDate) {
        return 1;
    }

    $days = max(1, (int) $startDate->diff($endDate)->format('%a') + 1);
    return max(1, (int) ceil($days / 30));
}

