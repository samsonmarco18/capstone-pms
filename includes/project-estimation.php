    <script>
    (function () {
        const salaries = <?php echo json_encode(PROJECT_ESTIMATION_SALARIES); ?>;
        const durationMonths = Number(document.getElementById('projectDurationMonths')?.value || 1);
        const techMonthly = Number(document.getElementById('techMonthlyTotal')?.value || 0);
        const clientBudget = <?php echo json_encode((float) ($project['sales_budget'] ?? 0)); ?>;
        const peso = new Intl.NumberFormat('en-PH', { style: 'currency', currency: 'PHP' });
        const estimationForm = document.getElementById('projectCostEstimationForm');
        const submissionStatus = document.querySelector('[data-project-estimation-submitted]');

        if (estimationForm && !estimationForm.classList.contains('is-locked')) {
            estimationForm.addEventListener('submit', () => {
                try {
                    sessionStorage.setItem('projectEstimationJustSubmitted', '1');
                } catch (error) {
                    // Submission still works when browser storage is unavailable.
                }
                const submitButton = estimationForm.querySelector('.project-estimation-submit');
                if (submitButton) {
                    submitButton.classList.add('is-loading');
                    submitButton.disabled = true;
                    submitButton.innerHTML = '<i class="fas fa-circle-notch fa-spin"></i> Submitting estimate...';
                }
            });
        }

        if (submissionStatus) {
            let shouldHighlightSubmission = false;
            try {
                shouldHighlightSubmission = sessionStorage.getItem('projectEstimationJustSubmitted') === '1';
                sessionStorage.removeItem('projectEstimationJustSubmitted');
            } catch (error) {
                shouldHighlightSubmission = false;
            }
            if (shouldHighlightSubmission) {
                window.setTimeout(() => {
                    submissionStatus.classList.add('is-arrival');
                    submissionStatus.scrollIntoView({ behavior: 'smooth', block: 'center' });
                    submissionStatus.focus({ preventScroll: true });
                }, 120);
            }
        }

        function updateProjectEstimation() {
            const groupedRows = new Map();
            let developerMonthly = 0;
            document.querySelectorAll('.allocation-input-row').forEach((row) => {
                const typeSelect = row.querySelector('.developer-type-input');
                const contributionInput = row.querySelector('.contribution-input');
                const type = typeSelect?.value || 'Professional Dev';
                const salary = Number(salaries[type] || 0);
                const contribution = Math.max(0, Math.min(100, Number(contributionInput?.value || 0)));
                if (contributionInput && Number(contributionInput.value || 0) !== contribution) {
                    contributionInput.value = contribution;
                }
                const contributionSalary = salary * (contribution / 100);
                developerMonthly += contributionSalary;
                const salaryCell = row.querySelector('.monthly-salary-cell');
                if (salaryCell) salaryCell.textContent = peso.format(salary);
                const current = groupedRows.get(type) || {
                    type,
                    salary,
                    contributionTotal: 0,
                    contributionSalary: 0,
                    count: 0
                };
                current.contributionTotal += contribution;
                current.contributionSalary += contributionSalary;
                current.count += 1;
                groupedRows.set(type, current);
            });

            const developerTotal = developerMonthly * durationMonths;
            const techTotal = techMonthly * durationMonths;
            const additional = Math.max(0, Number(document.getElementById('additionalCostsInput')?.value || 0));
            const overall = developerTotal + techTotal + additional;
            const remaining = clientBudget - overall;

            const tbody = document.getElementById('developerCostRows');
            if (tbody) {
                const rows = Array.from(groupedRows.values()).map((row) => ({
                    ...row,
                    averageContribution: row.count > 0 ? row.contributionTotal / row.count : 0
                }));
                tbody.innerHTML = rows.length ? rows.map((row) => `
                    <tr>
                        <td>${row.type}</td>
                        <td>${peso.format(row.salary)}</td>
                        <td>${row.averageContribution.toFixed(0)}% avg</td>
                        <td>${peso.format(row.contributionSalary)}</td>
                        <td>${row.count}</td>
                        <td>${peso.format(row.contributionSalary * durationMonths)}</td>
                        <td>${peso.format(techMonthly)}</td>
                        <td>${durationMonths} month${durationMonths === 1 ? '' : 's'}</td>
                        <td>${peso.format(techTotal)}</td>
                    </tr>
                `).join('') : '<tr><td colspan="9" class="text-muted">No developer rows to estimate.</td></tr>';
            }

            const setText = (id, value) => { const el = document.getElementById(id); if (el) el.textContent = peso.format(value); };
            setText('summaryDeveloperCost', developerTotal);
            setText('summaryTechCost', techTotal);
            setText('summaryAdditionalCost', additional);
            setText('summaryOverallCost', overall);
            setText('summaryRemainingBudget', remaining);
            document.getElementById('summaryRemainingBudget')?.classList.toggle('money-negative', remaining < 0);
            document.getElementById('summaryRemainingBudget')?.classList.toggle('money-positive', remaining >= 0);
        }

        document.addEventListener('input', (event) => {
            if (event.target.matches('.developer-type-input, .contribution-input, #additionalCostsInput')) {
                updateProjectEstimation();
            }
        });
        document.addEventListener('change', (event) => {
            if (event.target.matches('.developer-type-input')) {
                updateProjectEstimation();
            }
        });
        updateProjectEstimation();
    })();
    </script>
