function projectEstimationEnsureSchema(mysqli|PgsqlMysqliCompatConnection $conn): void
{
    if (dbTableExists($conn, 'expert_project_estimations')) {
        if (!dbColumnExists($conn, 'expert_project_estimations', 'workflow_version')) {
            try {
                $conn->query("ALTER TABLE expert_project_estimations ADD COLUMN workflow_version INT DEFAULT 1");
            } catch (Throwable $e) {
                error_log('Project estimation workflow migration column failed: ' . $e->getMessage());
            }
        }
        if (dbColumnExists($conn, 'expert_project_estimations', 'workflow_version')) {
            // Convert the previous Expert -> SUL -> Sales statuses once.
            // Old sales_approved rows were complete; old sul_approved rows
            // still need to enter the new Sales -> SUL review sequence.
            $conn->query("
                UPDATE expert_project_estimations
                SET status = CASE
                        WHEN status = 'sales_approved' THEN 'sul_approved'
                        WHEN status = 'sul_approved' THEN 'submitted'
                        ELSE status
                    END,
                    workflow_version = 2
                WHERE COALESCE(workflow_version, 1) < 2
            ");
        }
        return;
    }

    $jsonType = DB_DRIVER === 'pgsql' ? 'TEXT' : 'LONGTEXT';
    $statusType = DB_DRIVER === 'pgsql'
        ? "VARCHAR(40) DEFAULT 'draft'"
        : "ENUM('draft','submitted','sul_rejected','sul_approved','sales_rejected','sales_approved') DEFAULT 'draft'";
    $dateType = DB_DRIVER === 'pgsql' ? 'TIMESTAMP' : 'DATETIME';
    $idType = DB_DRIVER === 'pgsql' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INT PRIMARY KEY AUTO_INCREMENT';
    $uniqueSql = DB_DRIVER === 'pgsql' ? 'UNIQUE (project_id)' : 'UNIQUE KEY unique_project_estimation (project_id)';

    $conn->query("
        CREATE TABLE expert_project_estimations (
            id {$idType},
            project_id INT NOT NULL,
            expert_id INT NOT NULL,
            status {$statusType},
            project_duration_months INT DEFAULT 1,
            project_complexity VARCHAR(40) DEFAULT 'Medium',
            allocation_json {$jsonType} NULL,
            additional_costs DECIMAL(15, 2) DEFAULT 0,
            total_developer_cost DECIMAL(15, 2) DEFAULT 0,
            total_technology_stack_cost DECIMAL(15, 2) DEFAULT 0,
            overall_estimated_project_cost DECIMAL(15, 2) DEFAULT 0,
            remaining_budget DECIMAL(15, 2) DEFAULT 0,
            sul_reviewed_by INT NULL,
            sul_reviewed_at {$dateType} NULL,
            sul_comment TEXT NULL,
            sales_reviewed_by INT NULL,
            sales_reviewed_at {$dateType} NULL,
            sales_comment TEXT NULL,
            submitted_at {$dateType} NULL,
            approved_at {$dateType} NULL,
            workflow_version INT DEFAULT 2,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP" . (DB_DRIVER === 'pgsql' ? '' : ' ON UPDATE CURRENT_TIMESTAMP') . ",
            {$uniqueSql}
        )
    ");
}

function projectEstimationPeso(float|int|null $amount): string
{
    return '&#8369;' . number_format((float) $amount, 2);
}

function projectEstimationMonths(?string $start, ?string $end): int
{
    $startDate = $start ? DateTime::createFromFormat('Y-m-d', substr($start, 0, 10)) : false;
    $endDate = $end ? DateTime::createFromFormat('Y-m-d', substr($end, 0, 10)) : false;
    if (!$startDate || !$endDate || $endDate < $startDate) {
        return 1;
    }

    $days = max(1, (int) $startDate->diff($endDate)->format('%a') + 1);
    return max(1, (int) ceil($days / 30));
}

function projectEstimationDurationWindow(mysqli|PgsqlMysqliCompatConnection $conn, array $project): array
{
    $projectId = (int) ($project['id'] ?? 0);
    $fallbackStart = trim((string) ($project['timeline_start'] ?? ''));
    $fallbackEnd = trim((string) ($project['timeline_end'] ?? ''));
    $window = [
        'start' => $fallbackStart,
        'end' => $fallbackEnd,
        'label' => 'Project timeline',
        'phase_names' => [],
        'uses_phase_window' => false,
    ];

    if ($projectId <= 0 || !dbTableExists($conn, 'methodology_phases')) {
        return $window;
    }

    $phaseResult = $conn->query("
        SELECT name, start_date, end_date
        FROM methodology_phases
        WHERE project_id = {$projectId}
        ORDER BY COALESCE(NULLIF(sequence_no, 0), id) ASC, start_date ASC, id ASC
    ");
    if (!$phaseResult) {
        return $window;
    }

    $phases = [];
    while ($phase = $phaseResult->fetch_assoc()) {
        $phases[] = $phase;
    }

    $executionPhases = array_slice($phases, 1, 3);
    if (count($executionPhases) < 3) {
        return $window;
    }

    $starts = [];
    $ends = [];
    $phaseNames = [];
    foreach ($executionPhases as $phase) {
        $start = trim((string) ($phase['start_date'] ?? ''));
        $end = trim((string) ($phase['end_date'] ?? ''));
        if ($start === '' || $end === '') {
            return $window;
        }
        $starts[] = $start;
        $ends[] = $end;
        $phaseNames[] = trim((string) ($phase['name'] ?? 'Phase'));
    }

    sort($starts);
    sort($ends);

    return [
        'start' => $starts[0],
        'end' => end($ends) ?: $ends[0],
        'label' => implode(' + ', array_filter($phaseNames)) ?: 'Phases 2, 3, and 4',
        'phase_names' => $phaseNames,
        'uses_phase_window' => true,
    ];
}

function projectEstimationDurationMonths(mysqli|PgsqlMysqliCompatConnection $conn, array $project): int
{
    $window = projectEstimationDurationWindow($conn, $project);
    return projectEstimationMonths($window['start'] ?? null, $window['end'] ?? null);
}

