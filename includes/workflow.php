function workflowStatuses(): array
{
    return [
        'todo' => 'To Do',
        'in_progress' => 'In Progress',
        'in_review' => 'Estimation Review',
        'review' => 'Ready for Developer Assignment',
        'for_review' => 'For Review',
        'sul_revision' => 'SUL Revision',
        'qa_testing' => 'QA Testing',
        'qa_failed' => 'QA Needs Revision',
        'qa_passed' => 'QA Passed',
        'architect_review' => 'Architect Review',
        'merged' => 'Merged to Main',
        'ready_for_release' => 'Ready for Release',
        'completed' => 'Completed',
        'overdue' => 'Overdue',
        'blocked' => 'Blocked',
    ];
}

function workflowStatusLabel(string $status): string
{
    return workflowStatuses()[$status] ?? ucwords(str_replace('_', ' ', $status));
}

function workflowEnsureSchema(mysqli|PgsqlMysqliCompatConnection $conn): void
{
    static $done = false;
    if ($done) {
        return;
    }
    $done = true;

    if (defined('DB_DRIVER') && DB_DRIVER === 'mysql') {
        $conn->query("ALTER TABLE users MODIFY role ENUM('admin', 'sales', 'architect', 'sul', 'qa', 'expert', 'developer') NOT NULL");
        $conn->query("ALTER TABLE tasks MODIFY status ENUM('todo', 'in_progress', 'in_review', 'review', 'for_review', 'sul_revision', 'qa_testing', 'qa_failed', 'qa_passed', 'architect_review', 'merged', 'ready_for_release', 'completed', 'overdue', 'blocked') DEFAULT 'todo'");
    } elseif (defined('DB_DRIVER') && DB_DRIVER === 'pgsql') {
        $conn->query("ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check");
        $conn->query("ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('admin', 'sales', 'architect', 'sul', 'qa', 'expert', 'developer'))");
        $conn->query("ALTER TABLE tasks DROP CONSTRAINT IF EXISTS tasks_status_check");
        $conn->query("ALTER TABLE tasks ADD CONSTRAINT tasks_status_check CHECK (status IN ('todo', 'in_progress', 'in_review', 'review', 'for_review', 'sul_revision', 'qa_testing', 'qa_failed', 'qa_passed', 'architect_review', 'merged', 'ready_for_release', 'completed', 'overdue', 'blocked'))");
    }

    $timestampType = (defined('DB_DRIVER') && DB_DRIVER === 'pgsql') ? 'TIMESTAMP' : 'DATETIME';
    $workflowColumns = [
        'pr_submitted_at' => "{$timestampType} NULL",
        'sul_reviewed_by' => 'INT NULL',
        'sul_reviewed_at' => "{$timestampType} NULL",
        'qa_reviewed_by' => 'INT NULL',
        'qa_reviewed_at' => "{$timestampType} NULL",
        'architect_reviewed_by' => 'INT NULL',
        'architect_reviewed_at' => "{$timestampType} NULL",
        'merged_at' => "{$timestampType} NULL",
        'release_notified_at' => "{$timestampType} NULL",
    ];

    foreach ($workflowColumns as $column => $definition) {
        if (!dbColumnExists($conn, 'tasks', $column)) {
            $conn->query("ALTER TABLE tasks ADD COLUMN {$column} {$definition}");
        }
    }

    if (defined('DB_DRIVER') && DB_DRIVER === 'pgsql') {
        $conn->query(
            "CREATE TABLE IF NOT EXISTS qa_checklist_items (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                task_id INT NOT NULL,
                feature_name VARCHAR(150) NOT NULL,
                item_text VARCHAR(255) NOT NULL,
                status TEXT DEFAULT 'pending',
                notes TEXT,
                developer_id INT NULL,
                qa_user_id INT NULL,
                reviewed_at TIMESTAMP NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE,
                FOREIGN KEY (developer_id) REFERENCES users(id) ON DELETE SET NULL,
                FOREIGN KEY (qa_user_id) REFERENCES users(id) ON DELETE SET NULL
            )"
        );
    } else {
        $conn->query(
            "CREATE TABLE IF NOT EXISTS qa_checklist_items (
                id INT PRIMARY KEY AUTO_INCREMENT,
                task_id INT NOT NULL,
                feature_name VARCHAR(150) NOT NULL,
                item_text VARCHAR(255) NOT NULL,
                status ENUM('pending', 'passed', 'failed', 'needs_revision') DEFAULT 'pending',
                notes TEXT,
                developer_id INT NULL,
                qa_user_id INT NULL,
                reviewed_at DATETIME NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
                FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE,
                FOREIGN KEY (developer_id) REFERENCES users(id) ON DELETE SET NULL,
                FOREIGN KEY (qa_user_id) REFERENCES users(id) ON DELETE SET NULL,
                INDEX idx_task_id (task_id),
                INDEX idx_status (status)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
        );
    }
}

function workflowAddTaskComment(mysqli|PgsqlMysqliCompatConnection $conn, int $taskId, int $userId, string $comment): void
{
    $trimmed = trim($comment);
    if ($trimmed === '') {
        return;
    }

    $stmt = $conn->prepare('INSERT INTO task_comments (task_id, user_id, comment) VALUES (?, ?, ?)');
    if ($stmt === false) {
        return;
    }
    $stmt->bind_param('iis', $taskId, $userId, $trimmed);
    $stmt->execute();
    $stmt->close();
}

function workflowNotifyRoles(
    mysqli|PgsqlMysqliCompatConnection $conn,
    array $roles,
    string $title,
    string $message,
    string $actionUrl,
    int $relatedId,
    string $notificationType = 'approval',
    string $relatedTable = 'tasks'
): void {
    $safeRoles = array_values(array_filter(array_map(static fn($role): string => trim((string) $role), $roles)));
    if (!$safeRoles) {
        return;
    }

    $quotedRoles = array_map(static fn($role): string => "'" . $conn->real_escape_string($role) . "'", $safeRoles);
    $result = $conn->query('SELECT id FROM users WHERE role IN (' . implode(',', $quotedRoles) . ") AND status = 'active'");
    if (!$result) {
        return;
    }

    while ($recipient = $result->fetch_assoc()) {
        createNotification((int) $recipient['id'], $title, $message, $notificationType, $relatedTable, $relatedId, $actionUrl, false);
    }
}

function workflowNotifyUser(
    int $userId,
    string $title,
    string $message,
    string $actionUrl,
    int $relatedId
): void {
    if ($userId <= 0) {
        return;
    }
    createNotification($userId, $title, $message, 'task', 'tasks', $relatedId, $actionUrl, false);
}

function workflowLogStatusChange(int $userId, int $taskId, string $fromStatus, string $toStatus, string $action, ?string $comment = null): void
{
    logActivity(
        $userId,
        $action,
        'tasks',
        $taskId,
        ['status' => $fromStatus],
        ['status' => $toStatus, 'comment' => $comment],
        'success',
        trim(workflowStatusLabel($fromStatus) . ' → ' . workflowStatusLabel($toStatus) . ($comment ? ': ' . $comment : ''))
    );
}

function workflowEnsureDefaultQaChecklist(mysqli|PgsqlMysqliCompatConnection $conn, array $task): void
{
    $taskId = (int) ($task['id'] ?? 0);
    if ($taskId <= 0) {
        return;
    }

    $countStmt = $conn->prepare('SELECT COUNT(*) AS item_count FROM qa_checklist_items WHERE task_id = ?');
    if ($countStmt === false) {
        return;
    }
    $countStmt->bind_param('i', $taskId);
    $countStmt->execute();
    $row = $countStmt->get_result()->fetch_assoc();
    $countStmt->close();

    if ((int) ($row['item_count'] ?? 0) > 0) {
        return;
    }

    $featureName = trim((string) ($task['title'] ?? 'Feature'));
    $developerId = (int) ($task['assigned_to'] ?? 0);
    $defaultItems = [
        'Feature works according to the task requirements',
        'Validation and error messages display correctly',
        'Data loads and saves correctly',
        'Buttons and related functions work properly',
    ];

    $stmt = $conn->prepare('INSERT INTO qa_checklist_items (task_id, feature_name, item_text, developer_id) VALUES (?, ?, ?, ?)');
    if ($stmt === false) {
        return;
    }

    foreach ($defaultItems as $itemText) {
        $stmt->bind_param('issi', $taskId, $featureName, $itemText, $developerId);
        $stmt->execute();
    }
    $stmt->close();
}

function workflowMaybeCompleteProject(mysqli|PgsqlMysqliCompatConnection $conn, int $projectId): void
{
    if ($projectId <= 0) {
        return;
    }

    $stmt = $conn->prepare("SELECT COUNT(*) AS open_count FROM tasks WHERE project_id = ? AND status != 'completed'");
    if ($stmt === false) {
        return;
    }
    $stmt->bind_param('i', $projectId);
    $stmt->execute();
    $row = $stmt->get_result()->fetch_assoc();
    $stmt->close();

    if ((int) ($row['open_count'] ?? 0) === 0) {
        $updateStmt = $conn->prepare("UPDATE projects SET status = 'completed' WHERE id = ?");
        if ($updateStmt !== false) {
            $updateStmt->bind_param('i', $projectId);
            $updateStmt->execute();
            $updateStmt->close();
        }
    }
}
