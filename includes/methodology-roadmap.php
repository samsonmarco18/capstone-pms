<?php
declare(strict_types=1);

function methodologyRoadmapEnsureSchema(mysqli|PgsqlMysqliCompatConnection $conn): void
{
    if (!dbTableExists($conn, 'methodology_phases')) {
        $sql = DB_DRIVER === 'pgsql' ? "
            CREATE TABLE methodology_phases (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_id INT NOT NULL,
                name VARCHAR(150) NOT NULL,
                description TEXT,
                start_date DATE NOT NULL,
                end_date DATE NOT NULL,
                developer_count INT DEFAULT 0,
                sequence_no INT DEFAULT 0,
                status VARCHAR(30) DEFAULT 'planned',
                created_by INT NULL,
                updated_by INT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT fk_methodology_phase_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
                CONSTRAINT fk_methodology_phase_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_phase_updater FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
            )
        " : "
            CREATE TABLE methodology_phases (
                id INT PRIMARY KEY AUTO_INCREMENT,
                project_id INT NOT NULL,
                name VARCHAR(150) NOT NULL,
                description TEXT,
                start_date DATE NOT NULL,
                end_date DATE NOT NULL,
                developer_count INT DEFAULT 0,
                sequence_no INT DEFAULT 0,
                status ENUM('planned', 'in_progress', 'completed', 'on_hold') DEFAULT 'planned',
                created_by INT NULL,
                updated_by INT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
                CONSTRAINT fk_methodology_phase_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
                CONSTRAINT fk_methodology_phase_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_phase_updater FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL,
                INDEX idx_methodology_phase_project (project_id),
                INDEX idx_methodology_phase_dates (start_date, end_date)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
        ";
        $conn->query($sql);
    }

    if (!dbTableExists($conn, 'methodology_tasks')) {
        $sql = DB_DRIVER === 'pgsql' ? "
            CREATE TABLE methodology_tasks (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                phase_id INT NOT NULL,
                project_id INT NOT NULL,
                task_id INT NULL,
                title VARCHAR(255) NOT NULL,
                component_name VARCHAR(150),
                department VARCHAR(100),
                description TEXT,
                start_date DATE NOT NULL,
                end_date DATE NOT NULL,
                assigned_developer_id INT NULL,
                expert_people_count INT DEFAULT 0,
                expert_notes TEXT,
                status VARCHAR(30) DEFAULT 'planned',
                created_by INT NULL,
                updated_by INT NULL,
                expert_updated_by INT NULL,
                expert_updated_at TIMESTAMP NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT fk_methodology_task_phase FOREIGN KEY (phase_id) REFERENCES methodology_phases(id) ON DELETE CASCADE,
                CONSTRAINT fk_methodology_task_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
                CONSTRAINT fk_methodology_task_workflow_task FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_task_developer FOREIGN KEY (assigned_developer_id) REFERENCES users(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_task_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_task_updater FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_task_expert FOREIGN KEY (expert_updated_by) REFERENCES users(id) ON DELETE SET NULL
            )
        " : "
            CREATE TABLE methodology_tasks (
                id INT PRIMARY KEY AUTO_INCREMENT,
                phase_id INT NOT NULL,
                project_id INT NOT NULL,
                task_id INT NULL,
                title VARCHAR(255) NOT NULL,
                component_name VARCHAR(150),
                department VARCHAR(100),
                description TEXT,
                start_date DATE NOT NULL,
                end_date DATE NOT NULL,
                assigned_developer_id INT NULL,
                expert_people_count INT DEFAULT 0,
                expert_notes TEXT,
                status ENUM('planned', 'in_progress', 'completed', 'blocked') DEFAULT 'planned',
                created_by INT NULL,
                updated_by INT NULL,
                expert_updated_by INT NULL,
                expert_updated_at DATETIME NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
                CONSTRAINT fk_methodology_task_phase FOREIGN KEY (phase_id) REFERENCES methodology_phases(id) ON DELETE CASCADE,
                CONSTRAINT fk_methodology_task_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
                CONSTRAINT fk_methodology_task_workflow_task FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_task_developer FOREIGN KEY (assigned_developer_id) REFERENCES users(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_task_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_task_updater FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL,
                CONSTRAINT fk_methodology_task_expert FOREIGN KEY (expert_updated_by) REFERENCES users(id) ON DELETE SET NULL,
                INDEX idx_methodology_task_project (project_id),
                INDEX idx_methodology_task_phase (phase_id),
                INDEX idx_methodology_task_workflow_task (task_id),
                INDEX idx_methodology_task_dates (start_date, end_date),
                INDEX idx_methodology_task_developer (assigned_developer_id)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
        ";
        $conn->query($sql);
    } elseif (!dbColumnExists($conn, 'methodology_tasks', 'task_id')) {
        $conn->query("ALTER TABLE methodology_tasks ADD COLUMN task_id INT NULL");
    }
}

function methodologyRoadmapCompletion(mysqli|PgsqlMysqliCompatConnection $conn, int $projectId): array
{
    methodologyRoadmapEnsureSchema($conn);

    $featureCount = (int) (($conn->query("SELECT COUNT(*) AS total FROM tasks WHERE project_id = {$projectId} AND task_type = 'feature'")->fetch_assoc()['total'] ?? 0));
    $phaseCount = (int) (($conn->query("SELECT COUNT(*) AS total FROM methodology_phases WHERE project_id = {$projectId}")->fetch_assoc()['total'] ?? 0));
    $scheduledFeatureCount = (int) (($conn->query("
        SELECT COUNT(DISTINCT mt.task_id) AS total
        FROM methodology_tasks mt
        INNER JOIN tasks t ON t.id = mt.task_id
        WHERE mt.project_id = {$projectId}
          AND t.project_id = {$projectId}
          AND t.task_type = 'feature'
    ")->fetch_assoc()['total'] ?? 0));
    $unscheduledCount = max(0, $featureCount - $scheduledFeatureCount);

    return [
        'feature_count' => $featureCount,
        'phase_count' => $phaseCount,
        'scheduled_feature_count' => $scheduledFeatureCount,
        'unscheduled_count' => $unscheduledCount,
        'is_complete' => $featureCount > 0 && $phaseCount > 0 && $unscheduledCount === 0,
    ];
}

function methodologyRoadmapStartBlockReason(mysqli|PgsqlMysqliCompatConnection $conn, int $taskId, int $developerId): ?string
{
    methodologyRoadmapEnsureSchema($conn);

    $task = $conn->query("SELECT id, project_id FROM tasks WHERE id = {$taskId} AND assigned_to = {$developerId} LIMIT 1")->fetch_assoc();
    if (!$task) {
        return 'You can only start tasks assigned to you.';
    }

    $projectId = (int) ($task['project_id'] ?? 0);
    $phaseCount = (int) (($conn->query("SELECT COUNT(*) AS total FROM methodology_phases WHERE project_id = {$projectId}")->fetch_assoc()['total'] ?? 0));
    if ($phaseCount <= 0) {
        return null;
    }

    $roadmapTask = $conn->query("
        SELECT mt.start_date AS task_start, mt.end_date AS task_end, mt.assigned_developer_id,
               mp.name AS phase_name, mp.start_date AS phase_start, mp.end_date AS phase_end
        FROM methodology_tasks mt
        INNER JOIN methodology_phases mp ON mp.id = mt.phase_id
        WHERE mt.task_id = {$taskId}
          AND mt.project_id = {$projectId}
        ORDER BY mt.start_date ASC, mt.id ASC
        LIMIT 1
    ")->fetch_assoc();

    if (!$roadmapTask) {
        return 'This task is not scheduled in the methodology roadmap yet. Ask the architect to place it in a phase before starting.';
    }

    $assignedDeveloperId = (int) ($roadmapTask['assigned_developer_id'] ?? 0);
    if ($assignedDeveloperId > 0 && $assignedDeveloperId !== $developerId) {
        return 'This roadmap task is assigned to another developer in the methodology plan.';
    }

    $today = new DateTimeImmutable('today');
    $phaseStart = DateTimeImmutable::createFromFormat('!Y-m-d', (string) $roadmapTask['phase_start']);
    $taskStart = DateTimeImmutable::createFromFormat('!Y-m-d', (string) $roadmapTask['task_start']);

    if ($phaseStart && $today < $phaseStart) {
        return 'This phase has not started yet. Scheduled phase: ' . (string) $roadmapTask['phase_name'] . ' on ' . $phaseStart->format('M d, Y') . '.';
    }

    if ($taskStart && $today < $taskStart) {
        return 'This task is scheduled to start on ' . $taskStart->format('M d, Y') . ' in the methodology roadmap.';
    }

    return null;
}
