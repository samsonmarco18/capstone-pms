function methodologyRoadmapTemplateLabel(string $templateKey): string
{
    $templates = methodologyRoadmapTemplates();
    return (string) ($templates[$templateKey]['name'] ?? 'Custom');
}

function methodologyRoadmapDistributeTemplatePhases(array $project, string $templateKey): array
{
    $templates = methodologyRoadmapTemplates();
    if (!isset($templates[$templateKey])) {
        return [];
    }

    $projectStart = DateTimeImmutable::createFromFormat('!Y-m-d', (string) ($project['timeline_start'] ?? ''));
    $projectEnd = DateTimeImmutable::createFromFormat('!Y-m-d', (string) ($project['timeline_end'] ?? ''));
    if (!$projectStart || !$projectEnd || $projectEnd < $projectStart) {
        return [];
    }

    $phaseDefinitions = $templates[$templateKey]['phases'];
    $totalWeight = max(1, array_sum(array_map(static fn(array $phase): int => max(1, (int) ($phase['weight'] ?? 1)), $phaseDefinitions)));
    $totalDays = ((int) $projectStart->diff($projectEnd)->format('%a')) + 1;
    $remainingDays = $totalDays;
    $phaseCount = count($phaseDefinitions);
    $cursor = $projectStart;
    $phases = [];

    foreach ($phaseDefinitions as $index => $phase) {
        $remainingPhases = $phaseCount - $index;
        if ($remainingPhases === 1) {
            $duration = $remainingDays;
        } else {
            $duration = max(1, (int) round($totalDays * (max(1, (int) ($phase['weight'] ?? 1)) / $totalWeight)));
            $duration = min($duration, $remainingDays - ($remainingPhases - 1));
        }

        $end = $cursor->modify('+' . max(0, $duration - 1) . ' days');
        if ($end > $projectEnd || $remainingPhases === 1) {
            $end = $projectEnd;
        }

        $phases[] = [
            'name' => (string) ($phase['name'] ?? 'Phase'),
            'description' => (string) ($phase['description'] ?? ''),
            'start_date' => $cursor->format('Y-m-d'),
            'end_date' => $end->format('Y-m-d'),
            'developer_count' => 0,
            'sequence_no' => $index + 1,
            'status' => 'planned',
        ];

        $remainingDays -= $duration;
        $cursor = $end->modify('+1 day');
    }

    return $phases;
}

function methodologyRoadmapApplyTemplate(mysqli|PgsqlMysqliCompatConnection $conn, int $projectId, array $project, string $templateKey, int $userId, bool $replaceExisting): array
{
    methodologyRoadmapEnsureSchema($conn);
    $templates = methodologyRoadmapTemplates();
    if (!isset($templates[$templateKey])) {
        return ['success' => false, 'message' => 'Select a valid methodology template.'];
    }

    $existingPhaseCount = (int) (($conn->query("SELECT COUNT(*) AS total FROM methodology_phases WHERE project_id = {$projectId}")->fetch_assoc()['total'] ?? 0));
    if ($existingPhaseCount > 0 && !$replaceExisting) {
        return ['success' => false, 'message' => 'This project already has phases. Choose replace existing phases to apply a template again.'];
    }

    $templatePhases = methodologyRoadmapDistributeTemplatePhases($project, $templateKey);
    if ($templatePhases === []) {
        return ['success' => false, 'message' => 'Project start and end dates are required before applying a methodology template.'];
    }

    $conn->begin_transaction();

    try {
        if ($replaceExisting && $existingPhaseCount > 0) {
            $deleteStmt = $conn->prepare('DELETE FROM methodology_phases WHERE project_id = ?');
            if ($deleteStmt === false) {
                throw new RuntimeException('Unable to prepare existing roadmap cleanup.');
            }
            $deleteStmt->bind_param('i', $projectId);
            if (!$deleteStmt->execute()) {
                throw new RuntimeException('Unable to replace existing methodology phases.');
            }
            $deleteStmt->close();
        }

        $insertStmt = $conn->prepare("
            INSERT INTO methodology_phases (project_id, name, description, start_date, end_date, developer_count, sequence_no, status, created_by, updated_by)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ");
        if ($insertStmt === false) {
            throw new RuntimeException('Unable to prepare methodology phase generation.');
        }

        foreach ($templatePhases as $phase) {
            $phaseName = (string) $phase['name'];
            $phaseDescription = (string) $phase['description'];
            $phaseStart = (string) $phase['start_date'];
            $phaseEnd = (string) $phase['end_date'];
            $developerCount = (int) $phase['developer_count'];
            $sequenceNo = (int) $phase['sequence_no'];
            $status = (string) $phase['status'];
            $insertStmt->bind_param(
                'issssiisii',
                $projectId,
                $phaseName,
                $phaseDescription,
                $phaseStart,
                $phaseEnd,
                $developerCount,
                $sequenceNo,
                $status,
                $userId,
                $userId
            );
            if (!$insertStmt->execute()) {
                throw new RuntimeException('Unable to create methodology phase: ' . $phaseName);
            }
        }
        $insertStmt->close();

        if (dbColumnExists($conn, 'projects', 'methodology_template')) {
            $templateStmt = $conn->prepare('UPDATE projects SET methodology_template = ? WHERE id = ?');
            if ($templateStmt === false) {
                throw new RuntimeException('Unable to prepare template status update.');
            }
            $templateStmt->bind_param('si', $templateKey, $projectId);
            if (!$templateStmt->execute()) {
                throw new RuntimeException('Unable to update project template status.');
            }
            $templateStmt->close();
        }

        $conn->commit();
    } catch (Throwable $e) {
        $conn->rollback();
        error_log('Methodology template apply error: ' . $e->getMessage());

        return [
            'success' => false,
            'message' => 'Unable to apply methodology template. ' . $e->getMessage(),
        ];
    }

    return [
        'success' => true,
        'message' => methodologyRoadmapTemplateLabel($templateKey) . ' template applied with ' . count($templatePhases) . ' phases.',
    ];
}

function methodologyRoadmapCompletion(mysqli|PgsqlMysqliCompatConnection $conn, int $projectId): array
{
    methodologyRoadmapEnsureSchema($conn);

    $featureCount = (int) (($conn->query("SELECT COUNT(*) AS total FROM tasks WHERE project_id = {$projectId} AND task_type = 'feature'")->fetch_assoc()['total'] ?? 0));
    $phaseCount = (int) (($conn->query("SELECT COUNT(*) AS total FROM methodology_phases WHERE project_id = {$projectId}")->fetch_assoc()['total'] ?? 0));
    $scheduledFeatureCount = (int) (($conn->query("
        SELECT COUNT(DISTINCT mt.task_id) AS total
        FROM methodology_tasks mt
        INNER JOIN tasks t ON t.id = mt.task_id
        WHERE mt.project_id = {$projectId}
          AND t.project_id = {$projectId}
          AND t.task_type = 'feature'
    ")->fetch_assoc()['total'] ?? 0));
    $unscheduledCount = max(0, $featureCount - $scheduledFeatureCount);

    return [
        'feature_count' => $featureCount,
        'phase_count' => $phaseCount,
        'scheduled_feature_count' => $scheduledFeatureCount,
        'unscheduled_count' => $unscheduledCount,
        'is_complete' => $featureCount > 0 && $phaseCount > 0 && $unscheduledCount === 0,
    ];
}

function methodologyRoadmapStartBlockReason(mysqli|PgsqlMysqliCompatConnection $conn, int $taskId, int $developerId): ?string
{
    methodologyRoadmapEnsureSchema($conn);

    $task = $conn->query("
        SELECT t.id, t.project_id, u.department AS developer_department
        FROM tasks t
        LEFT JOIN users u ON u.id = t.assigned_to
        WHERE t.id = {$taskId} AND t.assigned_to = {$developerId}
        LIMIT 1
    ")->fetch_assoc();
    if (!$task) {
        return 'You can only start tasks assigned to you.';
    }

    $projectId = (int) ($task['project_id'] ?? 0);
    if (function_exists('projectWorkflowSyncRoadmap')) {
        projectWorkflowSyncRoadmap($conn, $projectId);
    }

    $phaseCount = (int) (($conn->query("SELECT COUNT(*) AS total FROM methodology_phases WHERE project_id = {$projectId}")->fetch_assoc()['total'] ?? 0));
    if ($phaseCount <= 0) {
        return null;
    }

    $developerDepartment = trim((string) ($task['developer_department'] ?? ''));
    $departmentFilter = '';
    if ($developerDepartment !== '' && function_exists('projectWorkflowMethodologyTaskDepartmentClause')) {
        $departmentFilter = ' OR ' . projectWorkflowMethodologyTaskDepartmentClause($conn, 'mt', $developerDepartment);
    }

    $roadmapTask = $conn->query("
        SELECT mt.start_date AS task_start, mt.end_date AS task_end, mt.assigned_developer_id, mt.department,
               mp.id AS phase_id, mp.sequence_no AS phase_sequence,
               mp.name AS phase_name, mp.start_date AS phase_start, mp.end_date AS phase_end
        FROM methodology_tasks mt
        INNER JOIN methodology_phases mp ON mp.id = mt.phase_id
        WHERE mt.task_id = {$taskId}
          AND mt.project_id = {$projectId}
          AND COALESCE(mt.status, 'planned') != 'completed'
          AND (mt.assigned_developer_id = {$developerId}{$departmentFilter})
        ORDER BY COALESCE(NULLIF(mp.sequence_no, 0), mp.id) ASC, mt.start_date ASC, mt.id ASC
        LIMIT 1
    ")->fetch_assoc();

    if (!$roadmapTask) {
        // Task allocation intentionally permits unscheduled feature tasks. The
        // developer assignment remains the source of truth until an architect
        // adds the task to a roadmap phase.
        return null;
    }

    $phaseId = (int) ($roadmapTask['phase_id'] ?? 0);
    $phaseSequence = (int) ($roadmapTask['phase_sequence'] ?? 0);
    $phasePosition = $phaseSequence > 0 ? $phaseSequence : $phaseId;
    $previousOpenCount = (int) (($conn->query("
        SELECT COUNT(*) AS total
        FROM methodology_phases
        WHERE project_id = {$projectId}
          AND id <> {$phaseId}
          AND COALESCE(NULLIF(sequence_no, 0), id) < {$phasePosition}
          AND status != 'completed'
    ")->fetch_assoc()['total'] ?? 0));
    if ($previousOpenCount > 0) {
        return 'Waiting for Previous Phase. This phase is visible but cannot start until earlier roadmap phases are completed.';
    }

    $assignedDeveloperId = (int) ($roadmapTask['assigned_developer_id'] ?? 0);
    if ($assignedDeveloperId > 0 && $assignedDeveloperId !== $developerId) {
        return 'This roadmap task is assigned to another developer in the methodology plan.';
    }

    $roadmapDepartment = (string) ($roadmapTask['department'] ?? '');
    $developerDepartment = (string) ($task['developer_department'] ?? '');
    $department = function_exists('projectWorkflowDepartmentLabel')
        ? projectWorkflowDepartmentLabel($roadmapDepartment !== '' ? $roadmapDepartment : $developerDepartment)
        : ($roadmapDepartment !== '' ? $roadmapDepartment : $developerDepartment);
    $canStartAfterPreviousPhases = in_array($department, ['Frontend', 'Backend'], true);
    if ($canStartAfterPreviousPhases) {
        return null;
    }

    $today = new DateTimeImmutable('today');
    $phaseStart = DateTimeImmutable::createFromFormat('!Y-m-d', (string) $roadmapTask['phase_start']);
    $taskStart = DateTimeImmutable::createFromFormat('!Y-m-d', (string) $roadmapTask['task_start']);

    if ($phaseStart && $today < $phaseStart) {
        return 'This phase has not started yet. Scheduled phase: ' . (string) $roadmapTask['phase_name'] . ' on ' . $phaseStart->format('M d, Y') . '.';
    }

    if ($taskStart && $today < $taskStart) {
        return 'This task is scheduled to start on ' . $taskStart->format('M d, Y') . ' in the methodology roadmap.';
    }

    return null;
}
