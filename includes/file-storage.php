<?php
declare(strict_types=1);

require_once __DIR__ . '/../config/database.php';

function storageEnsureDirectory(string $directory): void
{
    if (!is_dir($directory) && !mkdir($directory, 0755, true) && !is_dir($directory)) {
        throw new RuntimeException('Unable to create the configured upload directory.');
    }

    if (!is_writable($directory)) {
        error_log('Upload directory is not writable: ' . $directory);
        throw new RuntimeException('The configured upload directory is not writable.');
    }
}

function storageRootPath(): string
{
    return rtrim((string) UPLOAD_PATH, '/\\');
}

function storageUsesDatabase(): bool
{
    $backend = defined('UPLOAD_STORAGE_BACKEND')
        ? strtolower((string) UPLOAD_STORAGE_BACKEND)
        : strtolower((string) (getenv('UPLOAD_STORAGE_BACKEND') ?: 'filesystem'));

    return in_array($backend, ['db', 'database', 'postgres', 'pgsql'], true);
}

function storageEnsureBlobSchema(mysqli|PgsqlMysqliCompatConnection $conn): void
{
    static $done = false;
    if ($done) {
        return;
    }
    $done = true;

    if (dbTableExists($conn, 'upload_blobs')) {
        return;
    }

    if (defined('DB_DRIVER') && DB_DRIVER === 'pgsql') {
        $conn->query(
            "CREATE TABLE IF NOT EXISTS upload_blobs (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                relative_path TEXT NOT NULL UNIQUE,
                original_name TEXT,
                mime_type TEXT,
                file_size BIGINT NOT NULL DEFAULT 0,
                content_base64 TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )"
        );
        return;
    }

    $conn->query(
        "CREATE TABLE IF NOT EXISTS upload_blobs (
            id INT PRIMARY KEY AUTO_INCREMENT,
            relative_path VARCHAR(500) NOT NULL UNIQUE,
            original_name VARCHAR(255),
            mime_type VARCHAR(100),
            file_size BIGINT NOT NULL DEFAULT 0,
            content_base64 LONGTEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );
}

function storageBuildUploadTarget(string $originalName, ?string $subdirectory = null): array
{
    $cleanOriginalName = basename($originalName);
    $safeOriginalName = preg_replace('/[^A-Za-z0-9._-]/', '', $cleanOriginalName) ?: 'upload';
    $storedName = uniqid('file_', true) . '_' . $safeOriginalName;
    $relativeSubdirectory = trim(str_replace('\\', '/', $subdirectory ?: date('Y/m/d')), '/');
    if ($relativeSubdirectory === '' || str_contains($relativeSubdirectory, '..')) {
        throw new InvalidArgumentException('Invalid upload directory.');
    }

    $relativeDirectory = 'uploads/' . $relativeSubdirectory;
    $absoluteDirectory = storageRootPath() . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $relativeSubdirectory);

    storageEnsureDirectory($absoluteDirectory);

    return [
        'original_name' => $cleanOriginalName,
        'stored_name' => $storedName,
        'absolute_path' => $absoluteDirectory . DIRECTORY_SEPARATOR . $storedName,
        'relative_path' => $relativeDirectory . '/' . $storedName,
    ];
}

function storagePersistFile(string $relativePath, string $absolutePath, ?string $originalName = null, ?string $mimeType = null): void
{
    if (!storageUsesDatabase() || !is_file($absolutePath)) {
        return;
    }

    $relativePath = ltrim(trim(str_replace('\\', '/', $relativePath)), '/');
    if ($relativePath === '' || str_contains($relativePath, '..')) {
        throw new RuntimeException('Invalid upload path.');
    }

    $content = file_get_contents($absolutePath);
    if ($content === false) {
        throw new RuntimeException('Unable to read uploaded file for database storage.');
    }

    if ($mimeType === null || trim($mimeType) === '') {
        if (class_exists('finfo')) {
            $fileInfo = new finfo(FILEINFO_MIME_TYPE);
            $mimeType = (string) $fileInfo->file($absolutePath);
        } elseif (function_exists('mime_content_type')) {
            $mimeType = (string) mime_content_type($absolutePath);
        } else {
            $mimeType = 'application/octet-stream';
        }
    }

    $conn = getConnection();
    storageEnsureBlobSchema($conn);

    $delete = $conn->prepare('DELETE FROM upload_blobs WHERE relative_path = ?');
    if ($delete !== false) {
        $delete->bind_param('s', $relativePath);
        $delete->execute();
        $delete->close();
    }

    $encoded = base64_encode($content);
    $fileSize = strlen($content);
    $storedOriginal = trim((string) $originalName) !== '' ? (string) $originalName : basename($relativePath);
    $storedMime = trim((string) $mimeType) !== '' ? (string) $mimeType : 'application/octet-stream';

    $stmt = $conn->prepare(
        'INSERT INTO upload_blobs (relative_path, original_name, mime_type, file_size, content_base64)
         VALUES (?, ?, ?, ?, ?)'
    );
    if ($stmt === false) {
        throw new RuntimeException('Unable to prepare database upload storage.');
    }

    $stmt->bind_param('sssis', $relativePath, $storedOriginal, $storedMime, $fileSize, $encoded);
    if (!$stmt->execute()) {
        $error = $conn->error ?: 'unknown error';
        $stmt->close();
        throw new RuntimeException('Unable to store upload in database: ' . $error);
    }
    $stmt->close();
}

function storageMaterializeDatabaseFile(string $relativePath): ?string
{
    if (!storageUsesDatabase()) {
        return null;
    }

    $relativePath = ltrim(trim(str_replace('\\', '/', $relativePath)), '/');
    if ($relativePath === '' || str_contains($relativePath, '..')) {
        return null;
    }

    $conn = getConnection();
    storageEnsureBlobSchema($conn);

    $stmt = $conn->prepare('SELECT content_base64 FROM upload_blobs WHERE relative_path = ? LIMIT 1');
    if ($stmt === false) {
        return null;
    }
    $stmt->bind_param('s', $relativePath);
    if (!$stmt->execute()) {
        $stmt->close();
        return null;
    }

    $row = $stmt->get_result()->fetch_assoc();
    $stmt->close();
    if (!$row) {
        return null;
    }

    $content = base64_decode((string) ($row['content_base64'] ?? ''), true);
    if ($content === false) {
        return null;
    }

    $uploadRelativePath = str_starts_with($relativePath, 'uploads/')
        ? substr($relativePath, strlen('uploads/'))
        : $relativePath;
    $cachePath = storageRootPath()
        . DIRECTORY_SEPARATOR . '.db-cache'
        . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $uploadRelativePath);
    storageEnsureDirectory(dirname($cachePath));

    if (file_put_contents($cachePath, $content) === false) {
        return null;
    }

    return $cachePath;
}

function storageDeleteFile(string $relativePath): void
{
    $relativePath = ltrim(trim(str_replace('\\', '/', $relativePath)), '/');
    if ($relativePath === '' || str_contains($relativePath, '..')) {
        return;
    }

    $absolutePath = storageResolveRelativePath($relativePath);
    if ($absolutePath !== null && is_file($absolutePath)) {
        @unlink($absolutePath);
    }

    if (!storageUsesDatabase()) {
        return;
    }

    $conn = getConnection();
    storageEnsureBlobSchema($conn);
    $stmt = $conn->prepare('DELETE FROM upload_blobs WHERE relative_path = ?');
    if ($stmt !== false) {
        $stmt->bind_param('s', $relativePath);
        $stmt->execute();
        $stmt->close();
    }
}

function storageResolveRelativePath(string $relativePath): ?string
{
    $relativePath = trim(str_replace('\\', '/', $relativePath));
    if ($relativePath === '' || str_contains($relativePath, '..')) {
        return null;
    }

    $relativePath = ltrim($relativePath, '/');
    $uploadRelativePath = str_starts_with($relativePath, 'uploads/')
        ? substr($relativePath, strlen('uploads/'))
        : $relativePath;
    $rootPath = storageRootPath();
    $absolutePath = $rootPath . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $uploadRelativePath);
    $root = rtrim(str_replace('\\', '/', $rootPath), '/') . '/';
    $normalized = str_replace('\\', '/', $absolutePath);

    if (!str_starts_with($normalized, $root)) {
        return null;
    }

    if (!is_file($absolutePath)) {
        $databasePath = storageMaterializeDatabaseFile($relativePath);
        if ($databasePath !== null && is_file($databasePath)) {
            return $databasePath;
        }
    }

    // Backward compatibility for files created before UPLOAD_STORAGE_ROOT was configurable.
    if (!is_file($absolutePath) && str_starts_with($relativePath, 'uploads/')) {
        $legacyPath = APP_ROOT_PATH . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $relativePath);
        if (is_file($legacyPath)) {
            return $legacyPath;
        }
    }

    return $absolutePath;
}

function storagePublicUrl(string $relativePath): string
{
    $relativePath = ltrim(trim(str_replace('\\', '/', $relativePath)), '/');
    if ($relativePath === '') {
        return '';
    }

    $webRootUploads = rtrim(str_replace('\\', '/', APP_ROOT_PATH . '/uploads'), '/') . '/';
    $storageRoot = rtrim(str_replace('\\', '/', storageRootPath()), '/') . '/';

    if ($storageRoot === $webRootUploads) {
        return BASE_URL . $relativePath;
    }

    return BASE_URL . 'api/uploads/view.php?path=' . rawurlencode($relativePath);
}
