<?php
header('Content-Type: text/html');
require_once '../includes/auth.php';
requireRole('sales');

$conn = getConnection();
$id = $_GET['id'] ?? 0;

if (!$id) {
    die('Receipt ID required');
}

$receipt = $conn->query("
    SELECT r.*, sr.*, p.name as project_name, c.name as client_name, c.email, c.contact_person, c.phone, c.address, u.full_name as generated_by 
    FROM receipts r 
    JOIN sales_reports sr ON r.report_id = sr.id 
    JOIN projects p ON sr.project_id = p.id 
    JOIN clients c ON sr.client_id = c.id
    LEFT JOIN users u ON r.generated_by = u.id
    WHERE r.id = $id
")->fetch_assoc();

if (!$receipt) {
    die('Receipt not found');
}

$techQuery = $conn->query("
    SELECT t.name, tr.service_type, tr.estimated_cost, tr.quantity, tr.annual_cost 
    FROM tech_recommendations tr 
    JOIN technologies t ON tr.tech_id = t.id 
    WHERE tr.project_id = {$receipt['project_id']}
");
$techRows = '';
$totalTech = 0;
while ($tech = $techQuery->fetch_assoc()) {
    $amount = $tech['estimated_cost'] * ($tech['quantity'] ?: 1);
    $totalTech += $amount;
    $techRows .= '
        <tr>
            <td>' . htmlspecialchars($tech['name']) . ' (' . htmlspecialchars($tech['service_type']) . ')</td>
            <td>' . ($tech['quantity'] ?: 1) . '</td>
            <td>$' . number_format($tech['estimated_cost'], 2) . '</td>
            <td>$' . number_format($amount, 2) . '</td>
        </tr>';
}

$allocQuery = $conn->query("
    SELECT role, required_count FROM developer_allocations 
    WHERE project_id = {$receipt['project_id']}
");
$devRows = '';
$totalDev = 0;
$dailyRate = 500; // Configurable
while ($alloc = $allocQuery->fetch_assoc()) {
    $monthlyCost = $alloc['required_count'] * $dailyRate * 22; // 22 working days
    $totalDev += $monthlyCost;
    $devRows .= '
        <tr>
            <td>' . htmlspecialchars($alloc['role']) . '</td>
            <td>' . $alloc['required_count'] . '</td>
            <td>$' . number_format($dailyRate * 22, 2) . '/month</td>
            <td>$' . number_format($monthlyCost, 2) . '</td>
        </tr>';
}

$totalAmount = $receipt['amount_due'] ?? $receipt['total_cost'];

echo '
<!DOCTYPE html>
<html>
<head>
    <title>Receipt #' . htmlspecialchars($receipt['receipt_number']) . '</title>
    <style>
        body { font-family: "Segoe UI", Arial, sans-serif; margin: 0; padding: 40px; background: white; color: #333; }
        .receipt-container { max-width: 800px; margin: 0 auto; }
        .header { text-align: center; margin-bottom: 40px; border-bottom: 3px solid #0d556b; padding-bottom: 20px; }
        .company { font-size: 28px; font-weight: bold; color: #0d556b; margin-bottom: 10px; }
        .receipt-info { display: flex; justify-content: space-between; margin: 20px 0; font-size: 14px; }
        .table { width: 100%; border-collapse: collapse; margin: 30px 0; }
        .table th, .table td { border: 1px solid #ddd; padding: 12px; text-align: left; }
        .table th { background-color: #f8f9fa; font-weight: 600; color: #0d556b; }
        .total-row { font-size: 18px; font-weight: bold; background-color: #e3f2fd; }
        .total-amount { color: #0d556b; font-size: 24px; }
        .footer { margin-top: 40px; text-align: center; padding-top: 20px; border-top: 1px solid #eee; font-size: 12px; color: #666; }
        .status-badge { padding: 4px 8px; border-radius: 12px; font-size: 11px; font-weight: 500; }
        .status-paid { background: #d4edda; color: #155724; }
        .status-sent { background: #d1ecf1; color: #0c5460; }
        .status-overdue { background: #f8d7da; color: #721c24; }
        @media print { body { padding: 20px; } .no-print { display: none; } }
        @page { margin: 1in; }
    </style>
</head>
<body>
    <div class="receipt-container">
        <div class="header">
            <div class="company">ERNI Development Center Philippines Inc.</div>
            <div style="font-size: 18px; margin: 10px 0;">OFFICIAL RECEIPT</div>
            <div style="font-size: 16px; margin-bottom: 10px;">Receipt # ' . htmlspecialchars($receipt['receipt_number']) . '</div>
            <div>Date: ' . date('F d, Y') . ' | Time: ' . date('h:i A') . '</div>
        </div>

        <div class="receipt-info">
            <div>
                <strong>Bill To:</strong><br>
                ' . htmlspecialchars($receipt['client_name']) . '<br>
                Email: ' . htmlspecialchars($receipt['email']) . '<br>
                Phone: ' . htmlspecialchars($receipt['phone']) . '<br>
                Address: ' . htmlspecialchars($receipt['address']) . '
            </div>
            <div style="text-align: right;">
                <strong>Generated by:</strong><br>
                ' . htmlspecialchars($receipt['generated_by']) . '<br>
                Project: ' . htmlspecialchars($receipt['project_name']) . '
            </div>
        </div>

        <table class="table">
            <thead>
                <tr>
                    <th>Description</th>
                    <th>Quantity</th>
                    <th>Unit Price</th>
                    <th>Amount</th>
                </tr>
            </thead>
            <tbody>
                ' . $techRows . '
                ' . $devRows . '
                <tr class="total-row">
                    <td colspan="3"><strong>TOTAL AMOUNT DUE</strong></td>
                    <td class="total-amount">$' . number_format($totalAmount, 2) . '</td>
                </tr>
            </tbody>
        </table>

        <div class="footer">
            <p>Thank you for choosing ERNI Development Center Philippines Inc.</p>
            <p>Payment Terms: Net 30 days | VAT inclusive</p>
            <p>Questions? Contact billing@erni-pms.com</p>
            <button onclick="printReceipt()" class="no-print btn btn-primary">Print Receipt</button>
            <button onclick="downloadPDF()" class="no-print btn btn-success ml-2">Download PDF</button>
        </div>
    </div>

    <script src="https://cdnjs.cloudflare.com/ajax/libs/jspdf/2.5.1/jspdf.umd.min.js"></script>
    <script>
        function printReceipt() {
            window.print();
        }

        function downloadPDF() {
            const { jsPDF } = window.jspdf;
            const doc = new jsPDF();
            doc.html(document.querySelector(".receipt-container"), {
                callback: function (doc) {
                    doc.save("receipt_' . $receipt['receipt_number'] . '.pdf");
                },
                x: 10, y: 10, width: 190, windowWidth: 800
            });
        }
    </script>
</body>
</html>';
?>

