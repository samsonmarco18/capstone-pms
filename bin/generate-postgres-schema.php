<?php
declare(strict_types=1);

$root = dirname(__DIR__);
$sourcePath = $root . '/database.sql';
$targetPath = $root . '/database.postgres.sql';

$sql = file_get_contents($sourcePath);
if ($sql === false) {
    fwrite(STDERR, "Unable to read database.sql\n");
    exit(1);
}

$sql = str_replace("\r\n", "\n", $sql);
$sql = preg_replace('/^-- Create database.*?\nUSE\s+erni_pms;\n+/is', '', $sql) ?? $sql;
$sql = preg_replace('/^DROP DATABASE IF EXISTS .*?;\n?/im', '', $sql) ?? $sql;
$sql = preg_replace('/^CREATE DATABASE .*?;\n?/im', '', $sql) ?? $sql;
$sql = preg_replace('/^USE .*?;\n?/im', '', $sql) ?? $sql;

$updatedAtTables = [];
$indexes = [];

$sql = preg_replace_callback(
    '/CREATE TABLE\s+([a-zA-Z0-9_]+)\s*\((.*?)\)\s*ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;/is',
    static function (array $matches) use (&$updatedAtTables, &$indexes): string {
        $table = $matches[1];
        $body = $matches[2];
        $lines = preg_split('/\n/', $body) ?: [];
        $output = [];

        foreach ($lines as $line) {
            $trimmed = trim($line);
            if ($trimmed === '') {
                continue;
            }

            if (preg_match('/^INDEX\s+([a-zA-Z0-9_]+)\s*\((.+)\),?$/i', $trimmed, $indexMatch) === 1) {
                $indexes[] = sprintf(
                    'CREATE INDEX IF NOT EXISTS %s ON %s (%s);',
                    $table . '_' . $indexMatch[1],
                    $table,
                    $indexMatch[2]
                );
                continue;
            }

            $line = preg_replace(
                '/UNIQUE KEY\s+([a-zA-Z0-9_]+)\s*\((.+)\)/i',
                'CONSTRAINT $1 UNIQUE ($2)',
                $line
            ) ?? $line;
            $line = preg_replace('/\bINT PRIMARY KEY AUTO_INCREMENT\b/i', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $line) ?? $line;
            $line = preg_replace('/\bAUTO_INCREMENT\b/i', 'GENERATED BY DEFAULT AS IDENTITY', $line) ?? $line;
            $line = preg_replace('/\bLONGTEXT\b/i', 'TEXT', $line) ?? $line;
            $line = preg_replace('/\bDATETIME\b/i', 'TIMESTAMP', $line) ?? $line;
            $line = preg_replace('/\bBOOLEAN\b/i', 'SMALLINT', $line) ?? $line;
            $line = preg_replace('/\bTINYINT\s*\(\s*1\s*\)/i', 'SMALLINT', $line) ?? $line;
            $line = preg_replace('/DEFAULT\s+TRUE/i', 'DEFAULT 1', $line) ?? $line;
            $line = preg_replace('/DEFAULT\s+FALSE/i', 'DEFAULT 0', $line) ?? $line;
            $line = preg_replace('/CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP/i', 'CURRENT_TIMESTAMP', $line) ?? $line;

            if (preg_match('/^(\s*)([a-zA-Z0-9_]+)\s+ENUM\s*\(([^)]*)\)(.*)$/i', $line, $enumMatch) === 1) {
                $line = $enumMatch[1]
                    . $enumMatch[2]
                    . ' TEXT CHECK (' . $enumMatch[2] . ' IN (' . $enumMatch[3] . '))'
                    . $enumMatch[4];
            }

            if (stripos($line, 'updated_at ') !== false) {
                $updatedAtTables[$table] = true;
            }

            $output[] = rtrim($line);
        }

        $tableSql = "CREATE TABLE $table (\n" . implode("\n", $output) . "\n);\n";
        return preg_replace("/,\n\);/m", "\n);", $tableSql) ?? $tableSql;
    },
    $sql
) ?? $sql;

$sql = preg_replace('/DATE_ADD\s*\(\s*(.+?)\s*,\s*INTERVAL\s+(\d+)\s+(MINUTE|HOUR|DAY|MONTH|YEAR)\s*\)/i', '($1 + INTERVAL \'$2 $3\')', $sql) ?? $sql;
$sql = preg_replace('/DATE_SUB\s*\(\s*(.+?)\s*,\s*INTERVAL\s+(\d+)\s+(MINUTE|HOUR|DAY|MONTH|YEAR)\s*\)/i', '($1 - INTERVAL \'$2 $3\')', $sql) ?? $sql;
$sql = preg_replace('/\bCURDATE\(\)/i', 'CURRENT_DATE', $sql) ?? $sql;

$header = <<<SQL
-- PostgreSQL schema generated from database.sql
-- Target platform: Render Postgres
-- Notes:
-- 1. Render already creates the database, so this file creates tables only.
-- 2. Import this file into your Render Postgres instance.

CREATE OR REPLACE FUNCTION set_updated_at_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

SQL;

$triggerSql = '';
foreach (array_keys($updatedAtTables) as $table) {
    $triggerSql .= "DROP TRIGGER IF EXISTS trg_{$table}_updated_at ON {$table};\n";
    $triggerSql .= "CREATE TRIGGER trg_{$table}_updated_at\n";
    $triggerSql .= "BEFORE UPDATE ON {$table}\n";
    $triggerSql .= "FOR EACH ROW EXECUTE FUNCTION set_updated_at_timestamp();\n\n";
}

$finalSql = $header . "\n" . trim($sql) . "\n\n" . implode("\n", $indexes) . "\n\n" . $triggerSql;
$finalSql = preg_replace("/\n{3,}/", "\n\n", $finalSql) ?? $finalSql;

if (file_put_contents($targetPath, $finalSql) === false) {
    fwrite(STDERR, "Unable to write database.postgres.sql\n");
    exit(1);
}

fwrite(STDOUT, "Generated database.postgres.sql\n");
